/*
 * getObjectDescription: build an object description for messages
 *
 * The result is a palloc'd string.  NULL is returned for an undefined
 * object if missing_ok is true, else an error is generated.
 */
pub unsafe fn getObjectDescription(
    object: *const ObjectAddress,
    missing_ok: bool,
) -> *mut c_char {
    let mut buffer: StringInfoData = core::mem::zeroed();
    initStringInfo(&mut buffer);

    match (*object).classId {
        RelationRelationId => {
            if (*object).objectSubId == 0 {
                getRelationDescription(&mut buffer, (*object).objectId, missing_ok);
            } else {
                /* column, not whole relation */
                let mut rel: StringInfoData = core::mem::zeroed();
                let attname = get_attname((*object).objectId, (*object).objectSubId as AttrNumber, missing_ok);

                if attname.is_null() {
                    // break -- handled at end
                } else {
                    initStringInfo(&mut rel);
                    getRelationDescription(&mut rel, (*object).objectId, missing_ok);
                    /* translator: second %s is, e.g., "table %s" */
                    appendStringInfo!(&mut buffer, "column {} of {}",
                        core::ffi::CStr::from_ptr(attname).to_str().unwrap_or(""),
                        core::ffi::CStr::from_ptr(rel.data).to_str().unwrap_or(""));
                    pfree(rel.data as *mut c_void);
                }
            }
        }
        ProcedureRelationId => {
            let flags = FORMAT_PROC_INVALID_AS_NULL;
            let proname = format_procedure_extended((*object).objectId, flags);
            if !proname.is_null() {
                appendStringInfo!(&mut buffer, "function {}",
                    core::ffi::CStr::from_ptr(proname).to_str().unwrap_or(""));
            }
        }
        TypeRelationId => {
            let flags = FORMAT_TYPE_INVALID_AS_NULL;
            let typname = format_type_extended((*object).objectId, -1, flags);
            if !typname.is_null() {
                appendStringInfo!(&mut buffer, "type {}",
                    core::ffi::CStr::from_ptr(typname).to_str().unwrap_or(""));
            }
        }
        CastRelationId => {
            let cast_desc = table_open(CastRelationId, AccessShareLock);
            let mut skey: ScanKeyData = core::mem::zeroed();
            ScanKeyInit(&mut skey, Anum_pg_cast_oid, BTEqualStrategyNumber, F_OIDEQ,
                        ObjectIdGetDatum((*object).objectId));
            let rcscan = systable_beginscan(cast_desc, CastOidIndexId, true,
                                            core::ptr::null_mut(), 1, &mut skey);
            let tup = systable_getnext(rcscan);
            if !HeapTupleIsValid(tup) {
                if !missing_ok {
                    elog!(ERROR, "could not find tuple for cast {}", (*object).objectId);
                }
                systable_endscan(rcscan);
                table_close(cast_desc, AccessShareLock);
            } else {
                let cast_form = GETSTRUCT(tup) as Form_pg_cast;
                appendStringInfo!(&mut buffer, "cast from {} to {}",
                    core::ffi::CStr::from_ptr(format_type_be((*cast_form).castsource)).to_str().unwrap_or(""),
                    core::ffi::CStr::from_ptr(format_type_be((*cast_form).casttarget)).to_str().unwrap_or(""));
                systable_endscan(rcscan);
                table_close(cast_desc, AccessShareLock);
            }
        }
        CollationRelationId => {
            let coll_tup = SearchSysCache1(COLLOID, ObjectIdGetDatum((*object).objectId));
            if !HeapTupleIsValid(coll_tup) {
                if !missing_ok {
                    elog!(ERROR, "cache lookup failed for collation {}", (*object).objectId);
                }
            } else {
                let coll = GETSTRUCT(coll_tup) as Form_pg_collation;
                let nspname = if CollationIsVisible((*object).objectId) {
                    core::ptr::null_mut()
                } else {
                    get_namespace_name((*coll).collnamespace)
                };
                let qname = quote_qualified_identifier(nspname, (*coll).collname.data.as_ptr());
                appendStringInfo!(&mut buffer, "collation {}",
                    core::ffi::CStr::from_ptr(qname).to_str().unwrap_or(""));
                ReleaseSysCache(coll_tup);
            }
        }
        ConstraintRelationId => {
            let con_tup = SearchSysCache1(CONSTROID, ObjectIdGetDatum((*object).objectId));
            if !HeapTupleIsValid(con_tup) {
                if !missing_ok {
                    elog!(ERROR, "cache lookup failed for constraint {}", (*object).objectId);
                }
            } else {
                let con = GETSTRUCT(con_tup) as Form_pg_constraint;
                if OidIsValid((*con).conrelid) {
                    let mut rel: StringInfoData = core::mem::zeroed();
                    initStringInfo(&mut rel);
                    getRelationDescription(&mut rel, (*con).conrelid, false);
                    /* translator: second %s is, e.g., "table %s" */
                    appendStringInfo!(&mut buffer, "constraint {} on {}",
                        core::ffi::CStr::from_ptr((*con).conname.data.as_ptr()).to_str().unwrap_or(""),
                        core::ffi::CStr::from_ptr(rel.data).to_str().unwrap_or(""));
                    pfree(rel.data as *mut c_void);
                } else {
                    appendStringInfo!(&mut buffer, "constraint {}",
                        core::ffi::CStr::from_ptr((*con).conname.data.as_ptr()).to_str().unwrap_or(""));
                }
                ReleaseSysCache(con_tup);
            }
        }
        ConversionRelationId => {
            let con_tup = SearchSysCache1(CONVOID, ObjectIdGetDatum((*object).objectId));
            if !HeapTupleIsValid(con_tup) {
                if !missing_ok {
                    elog!(ERROR, "cache lookup failed for conversion {}", (*object).objectId);
                }
            } else {
                let conv = GETSTRUCT(con_tup) as Form_pg_conversion;
                let nspname = if ConversionIsVisible((*object).objectId) {
                    core::ptr::null_mut()
                } else {
                    get_namespace_name((*conv).connamespace)
                };
                let qname = quote_qualified_identifier(nspname, (*conv).conname.data.as_ptr());
                appendStringInfo!(&mut buffer, "conversion {}",
                    core::ffi::CStr::from_ptr(qname).to_str().unwrap_or(""));
                ReleaseSysCache(con_tup);
            }
        }
        AttrDefaultRelationId => {
            let colobject = GetAttrDefaultColumnAddress((*object).objectId);
            if !OidIsValid(colobject.objectId) {
                if !missing_ok {
                    elog!(ERROR, "could not find tuple for attrdef {}", (*object).objectId);
                }
            } else {
                let desc = getObjectDescription(&colobject, false);
                if !desc.is_null() {
                    /* translator: %s is typically "column %s of table %s" */
                    appendStringInfo!(&mut buffer, "default value for {}",
                        core::ffi::CStr::from_ptr(desc).to_str().unwrap_or(""));
                }
            }
        }
        LanguageRelationId => {
            let langname = get_language_name((*object).objectId, missing_ok);
            if !langname.is_null() {
                appendStringInfo!(&mut buffer, "language {}",
                    core::ffi::CStr::from_ptr(langname).to_str().unwrap_or(""));
            }
        }
        LargeObjectRelationId => {
            if LargeObjectExists((*object).objectId) {
                appendStringInfo!(&mut buffer, "large object {}", (*object).objectId);
            }
        }
        OperatorRelationId => {
            let flags = FORMAT_OPERATOR_INVALID_AS_NULL;
            let oprname = format_operator_extended((*object).objectId, flags);
            if !oprname.is_null() {
                appendStringInfo!(&mut buffer, "operator {}",
                    core::ffi::CStr::from_ptr(oprname).to_str().unwrap_or(""));
            }
        }
        OperatorClassRelationId => {
            let opc_tup = SearchSysCache1(CLAOID, ObjectIdGetDatum((*object).objectId));
            if !HeapTupleIsValid(opc_tup) {
                if !missing_ok {
                    elog!(ERROR, "cache lookup failed for opclass {}", (*object).objectId);
                }
            } else {
                let opc_form = GETSTRUCT(opc_tup) as Form_pg_opclass;
                let am_tup   = SearchSysCache1(AMOID, ObjectIdGetDatum((*opc_form).opcmethod));
                if !HeapTupleIsValid(am_tup) {
                    elog!(ERROR, "cache lookup failed for access method {}", (*opc_form).opcmethod);
                }
                let am_form = GETSTRUCT(am_tup) as Form_pg_am;
                let nspname = if OpclassIsVisible((*object).objectId) {
                    core::ptr::null_mut()
                } else {
                    get_namespace_name((*opc_form).opcnamespace)
                };
                let qname = quote_qualified_identifier(nspname, (*opc_form).opcname.data.as_ptr());
                appendStringInfo!(&mut buffer, "operator class {} for access method {}",
                    core::ffi::CStr::from_ptr(qname).to_str().unwrap_or(""),
                    core::ffi::CStr::from_ptr((*am_form).amname.data.as_ptr()).to_str().unwrap_or(""));
                ReleaseSysCache(am_tup);
                ReleaseSysCache(opc_tup);
            }
        }
        OperatorFamilyRelationId => {
            getOpFamilyDescription(&mut buffer, (*object).objectId, missing_ok);
        }
        AccessMethodRelationId => {
            let tup = SearchSysCache1(AMOID, ObjectIdGetDatum((*object).objectId));
            if !HeapTupleIsValid(tup) {
                if !missing_ok {
                    elog!(ERROR, "cache lookup failed for access method {}", (*object).objectId);
                }
            } else {
                appendStringInfo!(&mut buffer, "access method {}",
                    core::ffi::CStr::from_ptr(
                        (*(GETSTRUCT(tup) as Form_pg_am)).amname.data.as_ptr()
                    ).to_str().unwrap_or(""));
                ReleaseSysCache(tup);
            }
        }
        _ => {
            // The remaining large cases (amop, amproc, rule, trigger, etc.) are
            // handled in Part 7 via a helper dispatch.
            getObjectDescription_extended(&mut buffer, object, missing_ok);
        }
    }

    /* an empty buffer is equivalent to no object found */
    if buffer.len == 0 {
        return core::ptr::null_mut();
    }

    buffer.data
}

