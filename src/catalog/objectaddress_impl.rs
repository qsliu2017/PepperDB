/// appendStringInfo! macro wrapping lib::stringinfo::appendStringInfo.
///
/// Usage: appendStringInfo!(&mut buf, "{} foo {}", a, b)
/// Formats the string with Rust's format! then appends it.
macro_rules! appendStringInfo {
    ($buf:expr, $fmt:literal $(, $arg:expr)*) => {{
        let s = format!($fmt $(, $arg)*);
        let cs = format!("{}\0", s);
        $crate::lib::stringinfo::appendStringInfoString(
            $buf,
            cs.as_ptr() as *const core::ffi::c_char,
        );
    }};
}
