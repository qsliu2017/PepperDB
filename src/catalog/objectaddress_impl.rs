/*
 * Translate an object name and arguments (as passed by the parser) to an
 * ObjectAddress.
 *
 * The returned object will be locked using the specified lockmode.  If a
 * sub-object is looked up, the parent object will be locked instead.
 *
 * If the object is a relation or a child object of a relation (e.g. an
 * attribute or constraint), the relation is also opened and *relp receives
 * the open relcache entry pointer; otherwise, *relp is set to NULL.
 * (relp can be NULL if the caller never passes a relation-related object.)
 * Caller must close the relcache entry when done with it.  The relation is
 * locked with the specified lockmode if the target object is the relation
 * itself or an attribute, but for other child objects, only AccessShareLock
 * is acquired on the relation.
 *
 * If the object is not found, an error is thrown, unless missing_ok is true.
 * In that case, no lock is acquired, relp is set to NULL, and the returned
 * address has objectId set to InvalidOid.
 *
 * We don't currently provide a function to release the locks acquired here;
 * typically, the lock must be held until commit to guard against a concurrent
 * drop operation.
 */
pub unsafe fn get_object_address(
    objtype: ObjectType,
    object:  *mut Node,
    relp:    *mut Relation,
    lockmode: LOCKMODE,
    missing_ok: bool,
) -> ObjectAddress {
    let mut address = INVALID_OBJECT_ADDRESS;
    let mut old_address = INVALID_OBJECT_ADDRESS;
    let mut relation: Relation = core::ptr::null_mut();
    let mut inval_count: u64;

    /* Some kind of lock must be taken. */
    Assert!(lockmode != 0 /* NoLock */);

    'retry: loop {
        /*
         * Remember this value, so that, after looking up the object name and
         * locking it, we can check whether any invalidation messages have
         * been processed that might require a do-over.
         */
        inval_count = SharedInvalidMessageCounter();

        /* Look up object address. */
        match objtype {
            OBJECT_INDEX |
            OBJECT_SEQUENCE |
            OBJECT_TABLE |
            OBJECT_VIEW |
            OBJECT_MATVIEW |
            OBJECT_FOREIGN_TABLE => {
                address = get_relation_by_qualified_name(
                    objtype,
                    object as *mut List,
                    &mut relation,
                    lockmode,
                    missing_ok,
                );
            }
            OBJECT_ATTRIBUTE |
            OBJECT_COLUMN => {
                address = get_object_address_attribute(
                    objtype,
                    object as *mut List,
                    &mut relation,
                    lockmode,
                    missing_ok,
                );
            }
            OBJECT_DEFAULT => {
                address = get_object_address_attrdef(
                    objtype,
                    object as *mut List,
                    &mut relation,
                    lockmode,
                    missing_ok,
                );
            }
            OBJECT_RULE |
            OBJECT_TRIGGER |
            OBJECT_TABCONSTRAINT |
            OBJECT_POLICY => {
                address = get_object_address_relobject(
                    objtype,
                    object as *mut List,
                    &mut relation,
                    missing_ok,
                );
            }
            OBJECT_DOMCONSTRAINT => {
                let objlist = object as *mut List;
                let domaddr = get_object_address_type(
                    OBJECT_DOMAIN,
                    linitial(objlist) as *mut TypeName,
                    missing_ok,
                );
                let constrname = strVal(lsecond(objlist));
                address.classId     = ConstraintRelationId;
                address.objectId    = get_domain_constraint_oid(
                    domaddr.objectId,
                    constrname as *const c_char,
                    missing_ok,
                );
                address.objectSubId = 0;
            }
            OBJECT_DATABASE |
            OBJECT_EXTENSION |
            OBJECT_TABLESPACE |
            OBJECT_ROLE |
            OBJECT_SCHEMA |
            OBJECT_LANGUAGE |
            OBJECT_FDW |
            OBJECT_FOREIGN_SERVER |
            OBJECT_EVENT_TRIGGER |
            OBJECT_PARAMETER_ACL |
            OBJECT_ACCESS_METHOD |
            OBJECT_PUBLICATION |
            OBJECT_SUBSCRIPTION => {
                address = get_object_address_unqualified(
                    objtype,
                    object as *mut c_void, /* String * */
                    missing_ok,
                );
            }
            OBJECT_TYPE |
            OBJECT_DOMAIN => {
                address = get_object_address_type(
                    objtype,
                    object as *mut TypeName,
                    missing_ok,
                );
            }
            OBJECT_AGGREGATE |
            OBJECT_FUNCTION |
            OBJECT_PROCEDURE |
            OBJECT_ROUTINE => {
                address.classId     = ProcedureRelationId;
                address.objectId    = LookupFuncWithArgs(
                    objtype,
                    object as *mut ObjectWithArgs,
                    missing_ok,
                );
                address.objectSubId = 0;
            }
            OBJECT_OPERATOR => {
                address.classId     = OperatorRelationId;
                address.objectId    = LookupOperWithArgs(
                    object as *mut ObjectWithArgs,
                    missing_ok,
                );
                address.objectSubId = 0;
            }
            OBJECT_COLLATION => {
                address.classId     = CollationRelationId;
                address.objectId    = get_collation_oid(
                    object as *mut List,
                    missing_ok,
                );
                address.objectSubId = 0;
            }
            OBJECT_CONVERSION => {
                address.classId     = ConversionRelationId;
                address.objectId    = get_conversion_oid(
                    object as *mut List,
                    missing_ok,
                );
                address.objectSubId = 0;
            }
            OBJECT_OPCLASS |
            OBJECT_OPFAMILY => {
                address = get_object_address_opcf(
                    objtype,
                    object as *mut List,
                    missing_ok,
                );
            }
            OBJECT_AMOP |
            OBJECT_AMPROC => {
                address = get_object_address_opf_member(
                    objtype,
                    object as *mut List,
                    missing_ok,
                );
            }
            OBJECT_LARGEOBJECT => {
                address.classId     = LargeObjectRelationId;
                address.objectId    = oidparse(object);
                address.objectSubId = 0;
                if !LargeObjectExists(address.objectId) {
                    if !missing_ok {
                        ereport!(ERROR,
                            errmsg!("large object {} does not exist",
                                address.objectId));
                    }
                }
            }
            OBJECT_CAST => {
                let lst        = object as *mut List;
                let sourcetype = linitial(lst) as *mut TypeName;
                let targettype = lsecond(lst) as *mut TypeName;
                let sourcetypeid = LookupTypeNameOid(core::ptr::null_mut(), sourcetype, missing_ok);
                let targettypeid = LookupTypeNameOid(core::ptr::null_mut(), targettype, missing_ok);
                address.classId     = CastRelationId;
                address.objectId    = get_cast_oid(sourcetypeid, targettypeid, missing_ok);
                address.objectSubId = 0;
            }
            OBJECT_TRANSFORM => {
                let lst      = object as *mut List;
                let typename = linitial(lst) as *mut TypeName;
                let langname = strVal(lsecond(lst) as *mut c_void);
                let type_id  = LookupTypeNameOid(core::ptr::null_mut(), typename, missing_ok);
                let lang_id  = get_language_oid(langname as *const c_char, missing_ok);
                address.classId     = TransformRelationId;
                address.objectId    = get_transform_oid(type_id, lang_id, missing_ok);
                address.objectSubId = 0;
            }
            OBJECT_TSPARSER => {
                address.classId     = TSParserRelationId;
                address.objectId    = get_ts_parser_oid(object as *mut List, missing_ok);
                address.objectSubId = 0;
            }
            OBJECT_TSDICTIONARY => {
                address.classId     = TSDictionaryRelationId;
                address.objectId    = get_ts_dict_oid(object as *mut List, missing_ok);
                address.objectSubId = 0;
            }
            OBJECT_TSTEMPLATE => {
                address.classId     = TSTemplateRelationId;
                address.objectId    = get_ts_template_oid(object as *mut List, missing_ok);
                address.objectSubId = 0;
            }
            OBJECT_TSCONFIGURATION => {
                address.classId     = TSConfigRelationId;
                address.objectId    = get_ts_config_oid(object as *mut List, missing_ok);
                address.objectSubId = 0;
            }
            OBJECT_USER_MAPPING => {
                address = get_object_address_usermapping(
                    object as *mut List,
                    missing_ok,
                );
            }
            OBJECT_PUBLICATION_NAMESPACE => {
                address = get_object_address_publication_schema(
                    object as *mut List,
                    missing_ok,
                );
            }
            OBJECT_PUBLICATION_REL => {
                address = get_object_address_publication_rel(
                    object as *mut List,
                    &mut relation,
                    missing_ok,
                );
            }
            OBJECT_DEFACL => {
                address = get_object_address_defacl(
                    object as *mut List,
                    missing_ok,
                );
            }
            OBJECT_STATISTIC_EXT => {
                address.classId     = StatisticExtRelationId;
                address.objectId    = get_statistics_object_oid(
                    object as *mut List,
                    missing_ok,
                );
                address.objectSubId = 0;
            }
            /* no default, to let compiler warn about missing case */
            _ => {}
        }

        if address.classId == InvalidOid {
            elog!(ERROR, "unrecognized object type: {}", objtype as c_int);
        }

        /*
         * If we could not find the supplied object, return without locking.
         */
        if !OidIsValid(address.objectId) {
            Assert!(missing_ok);
            if relp.is_null() { /* caller didn't want relp */ } else { *relp = core::ptr::null_mut(); }
            return address;
        }

        /*
         * If we're retrying, see if we got the same answer as last time.  If
         * so, we're done; if not, we locked the wrong thing, so give up our
         * lock.
         */
        if OidIsValid(old_address.classId) {
            if old_address.classId    == address.classId
               && old_address.objectId == address.objectId
               && old_address.objectSubId == address.objectSubId
            {
                break 'retry;
            }
            if old_address.classId != RelationRelationId {
                if IsSharedRelation(old_address.classId) {
                    UnlockSharedObject(
                        old_address.classId,
                        old_address.objectId,
                        0, lockmode,
                    );
                } else {
                    UnlockDatabaseObject(
                        old_address.classId,
                        old_address.objectId,
                        0, lockmode,
                    );
                }
            }
        }

        /*
         * If we're dealing with a relation or attribute, then the relation is
         * already locked.  Otherwise, we lock it now.
         */
        if address.classId != RelationRelationId {
            if IsSharedRelation(address.classId) {
                LockSharedObject(address.classId, address.objectId, 0, lockmode);
            } else {
                LockDatabaseObject(address.classId, address.objectId, 0, lockmode);
            }
        }

        /*
         * At this point, we've resolved the name to an OID and locked the
         * corresponding database object.  However, it's possible that by the
         * time we acquire the lock on the object, concurrent DDL has modified
         * the database in such a way that the name we originally looked up no
         * longer resolves to that OID.
         *
         * We can be certain that this isn't an issue if (a) no shared
         * invalidation messages have been processed or (b) we've locked a
         * relation somewhere along the line.  All the relation name lookups
         * in this module ultimately use RangeVarGetRelid() to acquire a
         * relation lock, and that function protects against the same kinds of
         * races we're worried about here.  Even when operating on a
         * constraint, rule, or trigger, we still acquire AccessShareLock on
         * the relation, which is enough to freeze out any concurrent DDL.
         *
         * In all other cases, however, it's possible that the name we looked
         * up no longer refers to the object we locked, so we retry the lookup
         * and see whether we get the same answer.
         */
        if inval_count == SharedInvalidMessageCounter() || !relation.is_null() {
            break 'retry;
        }
        old_address = address;
    }

    /* relp must be given if it's a relation */
    Assert!(relation.is_null() || !relp.is_null());

    /* Return the object address and the relation. */
    if !relp.is_null() {
        *relp = relation;
    }
    address
}

/*
 * Return an ObjectAddress based on a RangeVar and an object name.  The
 * name of the relation identified by the RangeVar is prepended to the
 * (possibly empty) list passed in as object.  This is useful to find
 * the ObjectAddress of objects that depend on a relation.  All other
 * considerations are exactly as for get_object_address above.
 */
pub unsafe fn get_object_address_rv(
    objtype: ObjectType,
    rel: *mut RangeVar,
    mut object: *mut List,
    relp: *mut Relation,
    lockmode: LOCKMODE,
    missing_ok: bool,
) -> ObjectAddress {
    if !rel.is_null() {
        object = lcons(makeString((*rel).relname), object);
        if !(*rel).schemaname.is_null() {
            object = lcons(makeString((*rel).schemaname), object);
        }
        if !(*rel).catalogname.is_null() {
            object = lcons(makeString((*rel).catalogname), object);
        }
    }

    get_object_address(objtype, object as *mut Node, relp, lockmode, missing_ok)
}

