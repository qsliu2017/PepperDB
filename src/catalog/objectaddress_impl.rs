/*
 * Return whether we have useful data for the given object class in the
 * ObjectProperty table.
 */
pub unsafe fn is_objectclass_supported(class_id: Oid) -> bool {
    for entry in OBJECT_PROPERTY {
        if entry.class_oid == class_id {
            return true;
        }
    }
    false
}

/*
 * Find ObjectProperty structure by class_id.
 */
unsafe fn get_object_property_data(class_id: Oid) -> *const ObjectPropertyType {
    // Note: C uses a static cache variable; we do a simple linear scan here.
    for entry in OBJECT_PROPERTY {
        if entry.class_oid == class_id {
            return entry as *const ObjectPropertyType;
        }
    }

    ereport!(ERROR,
        errmsg!("unrecognized class ID: {}", class_id));

    core::ptr::null() /* keep MSC compiler happy */
}

/*
 * Return a copy of the tuple for the object with the given object OID, from
 * the given catalog (which must have been opened by the caller and suitably
 * locked).  NULL is returned if the OID is not found.
 *
 * We try a syscache first, if available.
 */
pub unsafe fn get_catalog_object_by_oid(
    catalog: Relation,
    oidcol: AttrNumber,
    object_id: Oid,
) -> HeapTuple {
    get_catalog_object_by_oid_extended(catalog, oidcol, object_id, false)
}

/*
 * Same as get_catalog_object_by_oid(), but with an additional "locktup"
 * argument controlling whether to acquire a LOCKTAG_TUPLE at mode
 * InplaceUpdateTupleLock.  See README.tuplock section "Locking to write
 * inplace-updated tables".
 */
pub unsafe fn get_catalog_object_by_oid_extended(
    catalog: Relation,
    oidcol: AttrNumber,
    object_id: Oid,
    locktup: bool,
) -> HeapTuple {
    let tuple: HeapTuple;
    let class_id = RelationGetRelid(catalog);
    let oid_cache_id = get_object_catcache_oid(class_id);

    if oid_cache_id > 0 {
        if locktup {
            tuple = SearchSysCacheLockedCopy1(
                oid_cache_id,
                ObjectIdGetDatum(object_id),
            );
        } else {
            tuple = SearchSysCacheCopy1(
                oid_cache_id,
                ObjectIdGetDatum(object_id),
            );
        }
        if !HeapTupleIsValid(tuple) {
            /* should not happen */
            return core::ptr::null_mut();
        }
    } else {
        let oid_index_id = get_object_oid_index(class_id);
        let scan: *mut SysScanDescData;
        let mut skey: ScanKeyData = core::mem::zeroed();

        Assert!(OidIsValid(oid_index_id));

        ScanKeyInit(
            &mut skey,
            oidcol,
            BTEqualStrategyNumber,
            F_OIDEQ,
            ObjectIdGetDatum(object_id),
        );

        scan  = systable_beginscan(catalog, oid_index_id, true,
                                   core::ptr::null_mut(), 1, &mut skey);
        let t = systable_getnext(scan);
        if !HeapTupleIsValid(t) {
            systable_endscan(scan);
            return core::ptr::null_mut();
        }

        if locktup {
            LockTuple(catalog, core::ptr::null_mut(), InplaceUpdateTupleLock);
        }

        let t_copy = heap_copytuple(t);

        systable_endscan(scan);
        return t_copy;
    }

    tuple
}

/*
 * getPublicationSchemaInfo
 *
 * Get publication name and schema name from the object address.
 */
unsafe fn getPublicationSchemaInfo(
    object: *const ObjectAddress,
    missing_ok: bool,
    pubname: *mut *mut c_char,
    nspname: *mut *mut c_char,
) -> bool {
    let tup: HeapTuple;
    let pnform: Form_pg_publication_namespace;

    tup = SearchSysCache1(PUBLICATIONNAMESPACE, ObjectIdGetDatum((*object).objectId));
    if !HeapTupleIsValid(tup) {
        if !missing_ok {
            elog!(ERROR, "cache lookup failed for publication schema {}", (*object).objectId);
        }
        return false;
    }

    pnform = GETSTRUCT(tup) as Form_pg_publication_namespace;
    *pubname = get_publication_name((*pnform).pnpubid, missing_ok);
    if (*pubname).is_null() {
        ReleaseSysCache(tup);
        return false;
    }

    *nspname = get_namespace_name((*pnform).pnnspid);
    if (*nspname).is_null() {
        let schemaid = (*pnform).pnnspid;
        pfree(*pubname as *mut c_void);
        ReleaseSysCache(tup);
        if !missing_ok {
            elog!(ERROR, "cache lookup failed for schema {}", schemaid);
        }
        return false;
    }

    ReleaseSysCache(tup);
    true
}

