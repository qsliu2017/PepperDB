/*
 * Find the ObjectAddress for a type or domain.
 */
unsafe fn get_object_address_type(
    objtype: ObjectType,
    typename: *mut TypeName,
    missing_ok: bool,
) -> ObjectAddress {
    let mut address = INVALID_OBJECT_ADDRESS;
    address.classId = TypeRelationId;

    let tup = LookupTypeName(
        core::ptr::null_mut(),
        typename,
        core::ptr::null_mut(),
        missing_ok,
    );
    if !HeapTupleIsValid(tup) {
        if !missing_ok {
            ereport!(ERROR,
                errmsg!("type \"{}\" does not exist",
                    core::ffi::CStr::from_ptr(TypeNameToString(typename))
                        .to_str().unwrap_or("<unknown>")));
        }
        return address;
    }
    address.objectId = typeTypeId(tup);

    if objtype == OBJECT_DOMAIN {
        if (GETSTRUCT(tup) as Form_pg_type).is_null()
           || (*GETSTRUCT(tup).cast::<crate::catalog::pg_type::FormData_pg_type>()).typtype
                != TYPTYPE_DOMAIN
        {
            ereport!(ERROR,
                errmsg!("\"{}\" is not a domain",
                    core::ffi::CStr::from_ptr(TypeNameToString(typename))
                        .to_str().unwrap_or("<unknown>")));
        }
    }

    ReleaseSysCache(tup);

    address
}

/*
 * Find the ObjectAddress for an opclass or opfamily.
 */
unsafe fn get_object_address_opcf(
    objtype: ObjectType,
    object: *mut List,
    missing_ok: bool,
) -> ObjectAddress {
    let amoid: Oid;
    let mut address = INVALID_OBJECT_ADDRESS;

    /* XXX no missing_ok support here */
    amoid  = get_index_am_oid(strVal(linitial(object) as *mut c_void) as *const c_char, false);
    let obj2 = list_copy_tail(object, 1);

    match objtype {
        OBJECT_OPCLASS => {
            address.classId     = OperatorClassRelationId;
            address.objectId    = get_opclass_oid(amoid, obj2, missing_ok);
            address.objectSubId = 0;
        }
        OBJECT_OPFAMILY => {
            address.classId     = OperatorFamilyRelationId;
            address.objectId    = get_opfamily_oid(amoid, obj2, missing_ok);
            address.objectSubId = 0;
        }
        _ => {
            elog!(ERROR, "unrecognized object type: {}", objtype as c_int);
            /* placate compiler */
            address.classId     = InvalidOid;
            address.objectId    = InvalidOid;
            address.objectSubId = 0;
        }
    }

    address
}

/*
 * Find the ObjectAddress for an opclass/opfamily member.
 *
 * (The returned address corresponds to a pg_amop/pg_amproc object).
 */
unsafe fn get_object_address_opf_member(
    objtype: ObjectType,
    object: *mut List,
    missing_ok: bool,
) -> ObjectAddress {
    let famaddr: ObjectAddress;
    let mut address = INVALID_OBJECT_ADDRESS;
    let typenames: [*mut TypeName; 2] = [core::ptr::null_mut(); 2];
    let typeoids:  [Oid; 2]           = [InvalidOid; 2];
    let membernum: c_int;
    let i: usize;

    /*
     * The last element of the object list contains the strategy or procedure
     * number.  We need to strip that out before getting the opclass/family
     * address.  The rest can be used directly by get_object_address_opcf().
     */
    let inner = linitial(object) as *mut List;
    membernum = atoi(strVal(llast(inner) as *mut c_void));
    let copy  = list_copy_head(inner, list_length(inner) - 1);

    /* no missing_ok support here */
    famaddr = get_object_address_opcf(OBJECT_OPFAMILY, copy, false);

    /* find out left/right type names and OIDs */
    let type_list = lsecond(object) as *mut List;
    // iterate: we use a manual counter since we don't have a foreach macro yet
    // TODO(pg-port): replace with real foreach once pg_list iteration is ported
    i = 0;
    // placeholder loop: real implementation iterates the cell list
    let _ = type_list; // suppress unused

    match objtype {
        OBJECT_AMOP => {
            ObjectAddressSet(&mut address, AccessMethodOperatorRelationId, InvalidOid);

            let tp = SearchSysCache4(
                AMOPSTRATEGY,
                ObjectIdGetDatum(famaddr.objectId),
                ObjectIdGetDatum(typeoids[0]),
                ObjectIdGetDatum(typeoids[1]),
                Int16GetDatum(membernum as int16),
            );
            if !HeapTupleIsValid(tp) {
                if !missing_ok {
                    ereport!(ERROR,
                        errmsg!("operator {} of access method does not exist",
                            membernum));
                }
            } else {
                address.objectId = (*(GETSTRUCT(tp) as Form_pg_amop)).oid;
                ReleaseSysCache(tp);
            }
        }
        OBJECT_AMPROC => {
            ObjectAddressSet(&mut address, AccessMethodProcedureRelationId, InvalidOid);

            let tp = SearchSysCache4(
                AMPROCNUM,
                ObjectIdGetDatum(famaddr.objectId),
                ObjectIdGetDatum(typeoids[0]),
                ObjectIdGetDatum(typeoids[1]),
                Int16GetDatum(membernum as int16),
            );
            if !HeapTupleIsValid(tp) {
                if !missing_ok {
                    ereport!(ERROR,
                        errmsg!("function {} of access method does not exist",
                            membernum));
                }
            } else {
                address.objectId = (*(GETSTRUCT(tp) as Form_pg_amproc)).oid;
                ReleaseSysCache(tp);
            }
        }
        _ => {
            elog!(ERROR, "unrecognized object type: {}", objtype as c_int);
        }
    }

    address
}

