/*
 * get_object_type
 *
 * Return the object type associated with a given object.
 */
pub unsafe fn get_object_type(class_id: Oid, object_id: Oid) -> ObjectType {
    let prop = get_object_property_data(class_id);

    if (*prop).objtype == OBJECT_TABLE as c_int {
        /*
         * If the property data says it's a table, dig a little deeper to get
         * the real relation kind, so that callers can produce more precise
         * error messages.
         */
        return get_relkind_objtype(get_rel_relkind(object_id));
    } else {
        // Safety: objtype was constructed from ObjectType cast; -1 means unsupported
        // but that would only arise for entries like role-membership where objtype == -1.
        // Treat -1 as OBJECT_TABLE as a fallback.
        if (*prop).objtype < 0 {
            return OBJECT_TABLE;
        }
        core::mem::transmute((*prop).objtype)
    }
}

