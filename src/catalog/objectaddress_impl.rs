unsafe fn getOpFamilyIdentity(
    buffer: *mut StringInfoData,
    opfid: Oid,
    object: *mut *mut List,
    missing_ok: bool,
) {
    let opf_tup = SearchSysCache1(OPFAMILYOID, ObjectIdGetDatum(opfid));
    if !HeapTupleIsValid(opf_tup) {
        if !missing_ok { elog!(ERROR, "cache lookup failed for opfamily {}", opfid); }
        return;
    }
    let opf_form = GETSTRUCT(opf_tup) as Form_pg_opfamily;

    let am_tup = SearchSysCache1(AMOID, ObjectIdGetDatum((*opf_form).opfmethod));
    if !HeapTupleIsValid(am_tup) {
        elog!(ERROR, "cache lookup failed for access method {}", (*opf_form).opfmethod);
    }
    let am_form = GETSTRUCT(am_tup) as Form_pg_am;

    let schema = get_namespace_name_or_temp((*opf_form).opfnamespace);
    let qname  = quote_qualified_identifier(schema, (*opf_form).opfname.data.as_ptr());
    let amname = quote_identifier((*am_form).amname.data.as_ptr());
    appendStringInfo!(&mut *buffer, "{} USING {}",
        core::ffi::CStr::from_ptr(qname).to_str().unwrap_or(""),
        core::ffi::CStr::from_ptr(amname).to_str().unwrap_or(""));

    if !object.is_null() {
        *object = list_make3(
            pstrdup((*am_form).amname.data.as_ptr() as _) as *mut c_void,
            pstrdup(schema as _) as *mut c_void,
            pstrdup((*opf_form).opfname.data.as_ptr() as _) as *mut c_void,
        );
    }

    ReleaseSysCache(am_tup);
    ReleaseSysCache(opf_tup);
}

/*
 * Append the relation identity (quoted qualified name) to the given StringInfo.
 */
unsafe fn getRelationIdentity(
    buffer: *mut StringInfoData,
    relid: Oid,
    object: *mut *mut List,
    missing_ok: bool,
) {
    let rel_tup = SearchSysCache1(RELOID, ObjectIdGetDatum(relid));
    if !HeapTupleIsValid(rel_tup) {
        if !missing_ok {
            elog!(ERROR, "cache lookup failed for relation {}", relid);
        }
        if !object.is_null() {
            *object = NIL;
        }
        return;
    }
    let rel_form = GETSTRUCT(rel_tup) as Form_pg_class;

    let schema = get_namespace_name_or_temp((*rel_form).relnamespace);
    let qname  = quote_qualified_identifier(schema, (*rel_form).relname.data.as_ptr());
    appendStringInfo!(&mut *buffer, "{}",
        core::ffi::CStr::from_ptr(qname).to_str().unwrap_or(""));
    if !object.is_null() {
        *object = list_make2(
            schema as *mut c_void,
            pstrdup((*rel_form).relname.data.as_ptr() as _) as *mut c_void,
        );
    }

    ReleaseSysCache(rel_tup);
}

/*
 * Auxiliary function to build a TEXT array out of a list of C-strings.
 */
pub unsafe fn strlist_to_textarray(list: *mut List) -> *mut c_void {
    let arr: *mut c_void;
    let datums: *mut Datum;
    let nulls: *mut bool;
    let mut j: c_int = 0;
    let memcxt: MemoryContext;
    let oldcxt: MemoryContext;
    let mut lb: [c_int; 1] = [0; 1];

    /* Work in a temp context; easier than individually pfree'ing the Datums */
    memcxt = AllocSetContextCreate!(
        CurrentMemoryContext,
        c"strlist to array".as_ptr(),
        ALLOCSET_DEFAULT_SIZES
    );
    oldcxt = MemoryContextSwitchTo(memcxt);

    datums = palloc(core::mem::size_of::<Datum>() * list_length(list) as usize) as *mut Datum;
    nulls = palloc(core::mem::size_of::<bool>() * list_length(list) as usize) as *mut bool;

    foreach!(cell, list, {
        let name: *mut c_char = lfirst(current_cell!(cell)) as *mut c_char;

        if !name.is_null() {
            *nulls.add(j as usize) = false;
            *datums.add(j as usize) = CStringGetTextDatum(name);
            j += 1;
        } else {
            *nulls.add(j as usize) = true;
        }
    });

    MemoryContextSwitchTo(oldcxt);

    lb[0] = 1;
    arr = construct_md_array(datums, nulls, 1, &mut j,
                            lb.as_mut_ptr(), TEXTOID, -1, false, TYPALIGN_INT);

    MemoryContextDelete(memcxt);

    arr
}

/*
 * get_relkind_objtype
 *
 * Return the object type for the relkind given by the caller.
 *
 * If an unexpected relkind is passed, we say OBJECT_TABLE rather than
 * failing.  That's because this is mostly used for generating error messages
 * for failed ACL checks on relations, and we'd rather produce a generic
 * message saying "table" than fail entirely.
 */
pub unsafe fn get_relkind_objtype(relkind: c_char) -> ObjectType {
    if relkind == RELKIND_RELATION as c_char || relkind == RELKIND_PARTITIONED_TABLE as c_char {
        OBJECT_TABLE
    } else if relkind == RELKIND_INDEX as c_char || relkind == RELKIND_PARTITIONED_INDEX as c_char {
        OBJECT_INDEX
    } else if relkind == RELKIND_SEQUENCE as c_char {
        OBJECT_SEQUENCE
    } else if relkind == RELKIND_VIEW as c_char {
        OBJECT_VIEW
    } else if relkind == RELKIND_MATVIEW as c_char {
        OBJECT_MATVIEW
    } else if relkind == RELKIND_FOREIGN_TABLE as c_char {
        OBJECT_FOREIGN_TABLE
    } else if relkind == RELKIND_TOASTVALUE as c_char {
        OBJECT_TABLE
    } else {
        /* Per above, don't raise an error */
        OBJECT_TABLE
    }
}

