/*
 * Find object address for an object that is attached to a relation.
 *
 * Note that we take only an AccessShareLock on the relation.  We need not
 * pass down the LOCKMODE from get_object_address(), because that is the lock
 * mode for the object itself, not the relation to which it is attached.
 */
unsafe fn get_object_address_relobject(
    objtype: ObjectType,
    object: *mut List,
    relp: *mut Relation,
    missing_ok: bool,
) -> ObjectAddress {
    let mut address = INVALID_OBJECT_ADDRESS;
    let mut relation: Relation = core::ptr::null_mut();
    let nnames: c_int;
    let depname: *const c_char;
    let relname: *mut List;
    let reloid: Oid;

    /* Extract name of dependent object. */
    depname = strVal(llast(object) as *mut c_void) as *const c_char;

    /* Separate relation name from dependent object name. */
    nnames = list_length(object);
    if nnames < 2 {
        ereport!(ERROR,
            errmsg!("must specify relation and object name"));
    }

    /* Extract relation name and open relation. */
    relname   = list_copy_head(object, nnames - 1);
    relation  = table_openrv_extended(
        makeRangeVarFromNameList(relname),
        AccessShareLock,
        missing_ok,
    );

    reloid = if !relation.is_null() { RelationGetRelid(relation) } else { InvalidOid };

    match objtype {
        OBJECT_RULE => {
            address.classId     = RewriteRelationId;
            address.objectId    = if !relation.is_null() {
                get_rewrite_oid(reloid, depname, missing_ok)
            } else { InvalidOid };
            address.objectSubId = 0;
        }
        OBJECT_TRIGGER => {
            address.classId     = TriggerRelationId;
            address.objectId    = if !relation.is_null() {
                get_trigger_oid(reloid, depname, missing_ok)
            } else { InvalidOid };
            address.objectSubId = 0;
        }
        OBJECT_TABCONSTRAINT => {
            address.classId     = ConstraintRelationId;
            address.objectId    = if !relation.is_null() {
                get_relation_constraint_oid(reloid, depname, missing_ok)
            } else { InvalidOid };
            address.objectSubId = 0;
        }
        OBJECT_POLICY => {
            address.classId     = PolicyRelationId;
            address.objectId    = if !relation.is_null() {
                get_relation_policy_oid(reloid, depname, missing_ok)
            } else { InvalidOid };
            address.objectSubId = 0;
        }
        _ => {
            elog!(ERROR, "unrecognized object type: {}", objtype as c_int);
        }
    }

    /* Avoid relcache leak when object not found. */
    if !OidIsValid(address.objectId) {
        if !relation.is_null() {
            table_close(relation, AccessShareLock);
        }
        relation = core::ptr::null_mut(); /* department of accident prevention */
        return address;
    }

    /* Done. */
    *relp = relation;
    address
}

/*
 * Find the ObjectAddress for an attribute.
 */
unsafe fn get_object_address_attribute(
    _objtype: ObjectType,
    object: *mut List,
    relp: *mut Relation,
    lockmode: LOCKMODE,
    missing_ok: bool,
) -> ObjectAddress {
    let mut address = INVALID_OBJECT_ADDRESS;
    let relname: *mut List;
    let reloid: Oid;
    let relation: Relation;
    let attname: *const c_char;
    let attnum: AttrNumber;

    /* Extract relation name and open relation. */
    if list_length(object) < 2 {
        ereport!(ERROR,
            errmsg!("column name must be qualified"));
    }
    attname = strVal(llast(object) as *mut c_void) as *const c_char;
    relname = list_copy_head(object, list_length(object) - 1);
    /* XXX no missing_ok support here */
    relation = relation_openrv(makeRangeVarFromNameList(relname), lockmode);
    reloid   = RelationGetRelid(relation);

    /* Look up attribute and construct return value. */
    attnum = get_attnum(reloid, attname);
    if attnum == InvalidAttrNumber {
        if !missing_ok {
            ereport!(ERROR,
                errmsg!("column of relation does not exist"));
        }
        address.classId     = RelationRelationId;
        address.objectId    = InvalidOid;
        address.objectSubId = InvalidAttrNumber as i32;
        relation_close(relation, lockmode);
        return address;
    }

    address.classId     = RelationRelationId;
    address.objectId    = reloid;
    address.objectSubId = attnum as i32;

    *relp = relation;
    address
}

