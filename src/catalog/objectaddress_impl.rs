/*
 * subroutine for getObjectDescription: describe a relation
 *
 * The result is appended to "buffer".
 */
unsafe fn getRelationDescription(buffer: *mut StringInfoData, relid: Oid, missing_ok: bool) {
    let rel_tup = SearchSysCache1(RELOID, ObjectIdGetDatum(relid));
    if !HeapTupleIsValid(rel_tup) {
        if !missing_ok {
            elog!(ERROR, "cache lookup failed for relation {}", relid);
        }
        return;
    }
    let rel_form = GETSTRUCT(rel_tup) as Form_pg_class;

    /* Qualify the name if not visible in search path */
    let nspname = if RelationIsVisible(relid) {
        core::ptr::null_mut()
    } else {
        get_namespace_name((*rel_form).relnamespace)
    };

    let relname = quote_qualified_identifier(nspname, (*rel_form).relname.data.as_ptr());
    let relname_s = core::ffi::CStr::from_ptr(relname).to_str().unwrap_or("");

    match (*rel_form).relkind {
        x if x == RELKIND_RELATION as c_char || x == RELKIND_PARTITIONED_TABLE as c_char => {
            appendStringInfo!(&mut *buffer, "table {}", relname_s);
        }
        x if x == RELKIND_INDEX as c_char || x == RELKIND_PARTITIONED_INDEX as c_char => {
            appendStringInfo!(&mut *buffer, "index {}", relname_s);
        }
        x if x == RELKIND_SEQUENCE as c_char => {
            appendStringInfo!(&mut *buffer, "sequence {}", relname_s);
        }
        x if x == RELKIND_TOASTVALUE as c_char => {
            appendStringInfo!(&mut *buffer, "toast table {}", relname_s);
        }
        x if x == RELKIND_VIEW as c_char => {
            appendStringInfo!(&mut *buffer, "view {}", relname_s);
        }
        x if x == RELKIND_MATVIEW as c_char => {
            appendStringInfo!(&mut *buffer, "materialized view {}", relname_s);
        }
        x if x == RELKIND_COMPOSITE_TYPE as c_char => {
            appendStringInfo!(&mut *buffer, "composite type {}", relname_s);
        }
        x if x == RELKIND_FOREIGN_TABLE as c_char => {
            appendStringInfo!(&mut *buffer, "foreign table {}", relname_s);
        }
        _ => {
            /* shouldn't get here */
            appendStringInfo!(&mut *buffer, "relation {}", relname_s);
        }
    }

    ReleaseSysCache(rel_tup);
}

