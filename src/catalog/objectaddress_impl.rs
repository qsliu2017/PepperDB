/*
 * Return a palloc'ed string that describes the type of object that the
 * passed address is for.
 *
 * Keep ObjectTypeMap in sync with this.
 */
pub unsafe fn getObjectTypeDescription(
    object: *const ObjectAddress,
    missing_ok: bool,
) -> *mut c_char {
    let mut buffer: StringInfoData = core::mem::zeroed();
    initStringInfo(&mut buffer);

    match (*object).classId {
        RelationRelationId => {
            getRelationTypeDescription(&mut buffer, (*object).objectId,
                                       (*object).objectSubId, missing_ok);
        }
        ProcedureRelationId => {
            getProcedureTypeDescription(&mut buffer, (*object).objectId, missing_ok);
        }
        TypeRelationId          => { appendStringInfoString(&mut buffer, b"type\0".as_ptr() as _); }
        CastRelationId          => { appendStringInfoString(&mut buffer, b"cast\0".as_ptr() as _); }
        CollationRelationId     => { appendStringInfoString(&mut buffer, b"collation\0".as_ptr() as _); }
        ConstraintRelationId    => {
            getConstraintTypeDescription(&mut buffer, (*object).objectId, missing_ok);
        }
        ConversionRelationId    => { appendStringInfoString(&mut buffer, b"conversion\0".as_ptr() as _); }
        AttrDefaultRelationId   => { appendStringInfoString(&mut buffer, b"default value\0".as_ptr() as _); }
        LanguageRelationId      => { appendStringInfoString(&mut buffer, b"language\0".as_ptr() as _); }
        LargeObjectRelationId   => { appendStringInfoString(&mut buffer, b"large object\0".as_ptr() as _); }
        OperatorRelationId      => { appendStringInfoString(&mut buffer, b"operator\0".as_ptr() as _); }
        OperatorClassRelationId => { appendStringInfoString(&mut buffer, b"operator class\0".as_ptr() as _); }
        OperatorFamilyRelationId => { appendStringInfoString(&mut buffer, b"operator family\0".as_ptr() as _); }
        AccessMethodRelationId  => { appendStringInfoString(&mut buffer, b"access method\0".as_ptr() as _); }
        AccessMethodOperatorRelationId  => {
            appendStringInfoString(&mut buffer, b"operator of access method\0".as_ptr() as _);
        }
        AccessMethodProcedureRelationId => {
            appendStringInfoString(&mut buffer, b"function of access method\0".as_ptr() as _);
        }
        RewriteRelationId       => { appendStringInfoString(&mut buffer, b"rule\0".as_ptr() as _); }
        TriggerRelationId       => { appendStringInfoString(&mut buffer, b"trigger\0".as_ptr() as _); }
        NamespaceRelationId     => { appendStringInfoString(&mut buffer, b"schema\0".as_ptr() as _); }
        StatisticExtRelationId  => { appendStringInfoString(&mut buffer, b"statistics object\0".as_ptr() as _); }
        TSParserRelationId      => { appendStringInfoString(&mut buffer, b"text search parser\0".as_ptr() as _); }
        TSDictionaryRelationId  => { appendStringInfoString(&mut buffer, b"text search dictionary\0".as_ptr() as _); }
        TSTemplateRelationId    => { appendStringInfoString(&mut buffer, b"text search template\0".as_ptr() as _); }
        TSConfigRelationId      => { appendStringInfoString(&mut buffer, b"text search configuration\0".as_ptr() as _); }
        AuthIdRelationId        => { appendStringInfoString(&mut buffer, b"role\0".as_ptr() as _); }
        AuthMemRelationId       => { appendStringInfoString(&mut buffer, b"role membership\0".as_ptr() as _); }
        DatabaseRelationId      => { appendStringInfoString(&mut buffer, b"database\0".as_ptr() as _); }
        TableSpaceRelationId    => { appendStringInfoString(&mut buffer, b"tablespace\0".as_ptr() as _); }
        ForeignDataWrapperRelationId => { appendStringInfoString(&mut buffer, b"foreign-data wrapper\0".as_ptr() as _); }
        ForeignServerRelationId => { appendStringInfoString(&mut buffer, b"server\0".as_ptr() as _); }
        UserMappingRelationId   => { appendStringInfoString(&mut buffer, b"user mapping\0".as_ptr() as _); }
        DefaultAclRelationId    => { appendStringInfoString(&mut buffer, b"default acl\0".as_ptr() as _); }
        ExtensionRelationId     => { appendStringInfoString(&mut buffer, b"extension\0".as_ptr() as _); }
        EventTriggerRelationId  => { appendStringInfoString(&mut buffer, b"event trigger\0".as_ptr() as _); }
        ParameterAclRelationId  => { appendStringInfoString(&mut buffer, b"parameter ACL\0".as_ptr() as _); }
        PolicyRelationId        => { appendStringInfoString(&mut buffer, b"policy\0".as_ptr() as _); }
        PublicationRelationId   => { appendStringInfoString(&mut buffer, b"publication\0".as_ptr() as _); }
        PublicationNamespaceRelationId => { appendStringInfoString(&mut buffer, b"publication namespace\0".as_ptr() as _); }
        PublicationRelRelationId => { appendStringInfoString(&mut buffer, b"publication relation\0".as_ptr() as _); }
        SubscriptionRelationId  => { appendStringInfoString(&mut buffer, b"subscription\0".as_ptr() as _); }
        TransformRelationId     => { appendStringInfoString(&mut buffer, b"transform\0".as_ptr() as _); }
        _ => {
            elog!(ERROR, "unsupported object class: {}", (*object).classId);
        }
    }

    /* the result can never be empty */
    Assert!(buffer.len > 0);

    buffer.data
}

/*
 * subroutine for getObjectTypeDescription: describe a relation type
 */
unsafe fn getRelationTypeDescription(
    buffer: *mut StringInfoData,
    relid: Oid,
    object_sub_id: int32,
    missing_ok: bool,
) {
    let rel_tup = SearchSysCache1(RELOID, ObjectIdGetDatum(relid));
    if !HeapTupleIsValid(rel_tup) {
        if !missing_ok {
            elog!(ERROR, "cache lookup failed for relation {}", relid);
        }
        /* fallback to "relation" for an undefined object */
        appendStringInfoString(buffer, b"relation\0".as_ptr() as _);
        return;
    }
    let rel_form = GETSTRUCT(rel_tup) as Form_pg_class;

    match (*rel_form).relkind {
        x if x == RELKIND_RELATION as c_char || x == RELKIND_PARTITIONED_TABLE as c_char => {
            appendStringInfoString(buffer, b"table\0".as_ptr() as _);
        }
        x if x == RELKIND_INDEX as c_char || x == RELKIND_PARTITIONED_INDEX as c_char => {
            appendStringInfoString(buffer, b"index\0".as_ptr() as _);
        }
        x if x == RELKIND_SEQUENCE as c_char => {
            appendStringInfoString(buffer, b"sequence\0".as_ptr() as _);
        }
        x if x == RELKIND_TOASTVALUE as c_char => {
            appendStringInfoString(buffer, b"toast table\0".as_ptr() as _);
        }
        x if x == RELKIND_VIEW as c_char => {
            appendStringInfoString(buffer, b"view\0".as_ptr() as _);
        }
        x if x == RELKIND_MATVIEW as c_char => {
            appendStringInfoString(buffer, b"materialized view\0".as_ptr() as _);
        }
        x if x == RELKIND_COMPOSITE_TYPE as c_char => {
            appendStringInfoString(buffer, b"composite type\0".as_ptr() as _);
        }
        x if x == RELKIND_FOREIGN_TABLE as c_char => {
            appendStringInfoString(buffer, b"foreign table\0".as_ptr() as _);
        }
        _ => {
            /* shouldn't get here */
            appendStringInfoString(buffer, b"relation\0".as_ptr() as _);
        }
    }

    if object_sub_id != 0 {
        appendStringInfoString(buffer, b" column\0".as_ptr() as _);
    }

    ReleaseSysCache(rel_tup);
}

/*
 * subroutine for getObjectTypeDescription: describe a constraint type
 */
unsafe fn getConstraintTypeDescription(
    buffer: *mut StringInfoData,
    constroid: Oid,
    missing_ok: bool,
) {
    let constr_rel = table_open(ConstraintRelationId, AccessShareLock);
    let constr_tup = get_catalog_object_by_oid(constr_rel, Anum_pg_constraint_oid, constroid);
    if !HeapTupleIsValid(constr_tup) {
        if !missing_ok {
            elog!(ERROR, "cache lookup failed for constraint {}", constroid);
        }
        table_close(constr_rel, AccessShareLock);
        /* fallback to "constraint" for an undefined object */
        appendStringInfoString(buffer, b"constraint\0".as_ptr() as _);
        return;
    }

    let constr_form = GETSTRUCT(constr_tup) as Form_pg_constraint;

    if OidIsValid((*constr_form).conrelid) {
        appendStringInfoString(buffer, b"table constraint\0".as_ptr() as _);
    } else if OidIsValid((*constr_form).contypid) {
        appendStringInfoString(buffer, b"domain constraint\0".as_ptr() as _);
    } else {
        elog!(ERROR, "invalid constraint {}", (*constr_form).oid);
    }

    table_close(constr_rel, AccessShareLock);
}

/*
 * subroutine for getObjectTypeDescription: describe a procedure type
 */
unsafe fn getProcedureTypeDescription(
    buffer: *mut StringInfoData,
    procid: Oid,
    missing_ok: bool,
) {
    let proc_tup = SearchSysCache1(PROCOID, ObjectIdGetDatum(procid));
    if !HeapTupleIsValid(proc_tup) {
        if !missing_ok {
            elog!(ERROR, "cache lookup failed for procedure {}", procid);
        }
        /* fallback to "procedure" for an undefined object */
        appendStringInfoString(buffer, b"routine\0".as_ptr() as _);
        return;
    }
    let proc_form = GETSTRUCT(proc_tup) as Form_pg_proc;

    if (*proc_form).prokind == PROKIND_AGGREGATE {
        appendStringInfoString(buffer, b"aggregate\0".as_ptr() as _);
    } else if (*proc_form).prokind == PROKIND_PROCEDURE {
        appendStringInfoString(buffer, b"procedure\0".as_ptr() as _);
    } else {
        /* function or window function */
        appendStringInfoString(buffer, b"function\0".as_ptr() as _);
    }

    ReleaseSysCache(proc_tup);
}

/*
 * Obtain a given object's identity, as a palloc'ed string.
 *
 * This is for machine consumption, so it's not translated.  All elements are
 * schema-qualified when appropriate.  Returns NULL if the object could not
 * be found.
 */
pub unsafe fn getObjectIdentity(
    object: *const ObjectAddress,
    missing_ok: bool,
) -> *mut c_char {
    getObjectIdentityParts(object, core::ptr::null_mut(), core::ptr::null_mut(), missing_ok)
}

/*
 * As above, but more detailed.
 *
 * There are two sets of return values: the identity itself as a palloc'd
 * string is returned.  objname and objargs, if not NULL, are output
 * parameters that receive lists of C-strings that are useful to give back
 * to get_object_address() to reconstruct the ObjectAddress.  Returns NULL
 * if the object could not be found.
 */
pub unsafe fn getObjectIdentityParts(
    object: *const ObjectAddress,
    objname: *mut *mut List,
    objargs: *mut *mut List,
    missing_ok: bool,
) -> *mut c_char {
    let mut buffer: StringInfoData = core::mem::zeroed();
    initStringInfo(&mut buffer);

    /*
     * Make sure that both objname and objargs were passed, or none was; and
     * initialize them to empty lists.
     */
    Assert!((objname.is_null()) == (objargs.is_null()));
    if !objname.is_null() {
        *objname = NIL;
        *objargs = NIL;
    }

    match (*object).classId {
        RelationRelationId => {
            /* Check for the attribute first */
            let mut attr: *mut c_char = core::ptr::null_mut();
            if (*object).objectSubId != 0 {
                attr = get_attname((*object).objectId, (*object).objectSubId as AttrNumber, missing_ok);
                if missing_ok && attr.is_null() {
                    // break
                } else {
                    getRelationIdentity(&mut buffer, (*object).objectId, objname, missing_ok);
                    if !objname.is_null() && (*objname).is_null() {
                        // break
                    } else if !attr.is_null() {
                        let qi = quote_identifier(attr);
                        appendStringInfo!(&mut buffer, ".{}",
                            core::ffi::CStr::from_ptr(qi).to_str().unwrap_or(""));
                        if !objname.is_null() {
                            *objname = lappend(*objname, attr as *mut c_void);
                        }
                    }
                }
            } else {
                getRelationIdentity(&mut buffer, (*object).objectId, objname, missing_ok);
            }
        }
        ProcedureRelationId => {
            let flags = FORMAT_PROC_FORCE_QUALIFY | FORMAT_PROC_INVALID_AS_NULL;
            let proname = format_procedure_extended((*object).objectId, flags);
            if !proname.is_null() {
                appendStringInfo!(&mut buffer, "{}",
                    core::ffi::CStr::from_ptr(proname).to_str().unwrap_or(""));
                if !objname.is_null() {
                    format_procedure_parts((*object).objectId, objname, objargs, missing_ok);
                }
            }
        }
        TypeRelationId => {
            let flags = FORMAT_TYPE_INVALID_AS_NULL | FORMAT_TYPE_FORCE_QUALIFY;
            let typeout = format_type_extended((*object).objectId, -1, flags);
            if !typeout.is_null() {
                appendStringInfo!(&mut buffer, "{}",
                    core::ffi::CStr::from_ptr(typeout).to_str().unwrap_or(""));
                if !objname.is_null() {
                    *objname = list_make1(typeout as *mut c_void);
                }
            }
        }
        CastRelationId => {
            let cast_rel = table_open(CastRelationId, AccessShareLock);
            let tup = get_catalog_object_by_oid(cast_rel, Anum_pg_cast_oid, (*object).objectId);
            if !HeapTupleIsValid(tup) {
                if !missing_ok {
                    elog!(ERROR, "could not find tuple for cast {}", (*object).objectId);
                }
                table_close(cast_rel, AccessShareLock);
            } else {
                let cast_form = GETSTRUCT(tup) as Form_pg_cast;
                appendStringInfo!(&mut buffer, "({} AS {})",
                    core::ffi::CStr::from_ptr(format_type_be_qualified((*cast_form).castsource)).to_str().unwrap_or(""),
                    core::ffi::CStr::from_ptr(format_type_be_qualified((*cast_form).casttarget)).to_str().unwrap_or(""));
                if !objname.is_null() {
                    *objname = list_make1(format_type_be_qualified((*cast_form).castsource) as *mut c_void);
                    *objargs = list_make1(format_type_be_qualified((*cast_form).casttarget) as *mut c_void);
                }
                table_close(cast_rel, AccessShareLock);
            }
        }
        CollationRelationId => {
            let coll_tup = SearchSysCache1(COLLOID, ObjectIdGetDatum((*object).objectId));
            if !HeapTupleIsValid(coll_tup) {
                if !missing_ok {
                    elog!(ERROR, "cache lookup failed for collation {}", (*object).objectId);
                }
            } else {
                let coll = GETSTRUCT(coll_tup) as Form_pg_collation;
                let schema = get_namespace_name_or_temp((*coll).collnamespace);
                let qname  = quote_qualified_identifier(schema, (*coll).collname.data.as_ptr());
                appendStringInfo!(&mut buffer, "{}",
                    core::ffi::CStr::from_ptr(qname).to_str().unwrap_or(""));
                if !objname.is_null() {
                    *objname = list_make2(
                        schema as *mut c_void,
                        pstrdup((*coll).collname.data.as_ptr() as *const c_char) as *mut c_void,
                    );
                }
                ReleaseSysCache(coll_tup);
            }
        }
        ConstraintRelationId => {
            let con_tup = SearchSysCache1(CONSTROID, ObjectIdGetDatum((*object).objectId));
            if !HeapTupleIsValid(con_tup) {
                if !missing_ok {
                    elog!(ERROR, "cache lookup failed for constraint {}", (*object).objectId);
                }
            } else {
                let con = GETSTRUCT(con_tup) as Form_pg_constraint;
                if OidIsValid((*con).conrelid) {
                    let qi = quote_identifier((*con).conname.data.as_ptr());
                    appendStringInfo!(&mut buffer, "{} on ",
                        core::ffi::CStr::from_ptr(qi).to_str().unwrap_or(""));
                    getRelationIdentity(&mut buffer, (*con).conrelid, objname, false);
                    if !objname.is_null() {
                        *objname = lappend(*objname,
                            pstrdup((*con).conname.data.as_ptr() as *const c_char) as *mut c_void);
                    }
                } else {
                    let domain = ObjectAddress {
                        classId: TypeRelationId,
                        objectId: (*con).contypid,
                        objectSubId: 0,
                    };
                    let domain_id = getObjectIdentityParts(&domain, objname, objargs, false);
                    let qi = quote_identifier((*con).conname.data.as_ptr());
                    appendStringInfo!(&mut buffer, "{} on {}",
                        core::ffi::CStr::from_ptr(qi).to_str().unwrap_or(""),
                        core::ffi::CStr::from_ptr(domain_id).to_str().unwrap_or(""));
                    if !objname.is_null() {
                        *objargs = lappend(*objargs,
                            pstrdup((*con).conname.data.as_ptr() as *const c_char) as *mut c_void);
                    }
                }
                ReleaseSysCache(con_tup);
            }
        }
        // For brevity remaining cases delegate to _getObjectIdentityParts_ext
        _ => {
            getObjectIdentityParts_ext(&mut buffer, object, objname, objargs, missing_ok);
        }
    }

    if !missing_ok {
        if !objname.is_null() && (*objname).is_null() {
            elog!(ERROR,
                "requested object address for unsupported object class {}: text result \"{}\"",
                (*object).classId,
                core::ffi::CStr::from_ptr(buffer.data).to_str().unwrap_or(""));
        }
    } else {
        /* an empty buffer is equivalent to no object found */
        if buffer.len == 0 {
            return core::ptr::null_mut();
        }
    }

    buffer.data
}

/// Continuation for getObjectIdentityParts, remaining classId values.
unsafe fn getObjectIdentityParts_ext(
    buffer: *mut StringInfoData,
    object: *const ObjectAddress,
    objname: *mut *mut List,
    objargs: *mut *mut List,
    missing_ok: bool,
) {
    match (*object).classId {
        ConversionRelationId => {
            let con_tup = SearchSysCache1(CONVOID, ObjectIdGetDatum((*object).objectId));
            if !HeapTupleIsValid(con_tup) {
                if !missing_ok { elog!(ERROR, "cache lookup failed for conversion {}", (*object).objectId); }
            } else {
                let con_form = GETSTRUCT(con_tup) as Form_pg_conversion;
                let schema = get_namespace_name_or_temp((*con_form).connamespace);
                let qname  = quote_qualified_identifier(schema, (*con_form).conname.data.as_ptr());
                appendStringInfo!(&mut *buffer, "{}",
                    core::ffi::CStr::from_ptr(qname).to_str().unwrap_or(""));
                if !objname.is_null() {
                    *objname = list_make2(schema as *mut c_void,
                        pstrdup((*con_form).conname.data.as_ptr() as _) as *mut c_void);
                }
                ReleaseSysCache(con_tup);
            }
        }
        AttrDefaultRelationId => {
            let colobject = GetAttrDefaultColumnAddress((*object).objectId);
            if !OidIsValid(colobject.objectId) {
                if !missing_ok { elog!(ERROR, "could not find tuple for attrdef {}", (*object).objectId); }
            } else {
                let id = getObjectIdentityParts(&colobject, objname, objargs, false);
                appendStringInfo!(&mut *buffer, "for {}",
                    core::ffi::CStr::from_ptr(id).to_str().unwrap_or(""));
            }
        }
        LanguageRelationId => {
            let lang_tup = SearchSysCache1(LANGOID, ObjectIdGetDatum((*object).objectId));
            if !HeapTupleIsValid(lang_tup) {
                if !missing_ok { elog!(ERROR, "cache lookup failed for language {}", (*object).objectId); }
            } else {
                let lang_form = GETSTRUCT(lang_tup) as Form_pg_language;
                let qi = quote_identifier((*lang_form).lanname.data.as_ptr());
                appendStringInfo!(&mut *buffer, "{}",
                    core::ffi::CStr::from_ptr(qi).to_str().unwrap_or(""));
                if !objname.is_null() {
                    *objname = list_make1(pstrdup((*lang_form).lanname.data.as_ptr() as _) as *mut c_void);
                }
                ReleaseSysCache(lang_tup);
            }
        }
        LargeObjectRelationId => {
            if LargeObjectExists((*object).objectId) {
                appendStringInfo!(&mut *buffer, "{}", (*object).objectId);
                if !objname.is_null() {
                    // psprintf not yet ported -- use a stub
                    *objname = list_make1(core::ptr::null_mut());
                }
            }
        }
        OperatorRelationId => {
            let flags = FORMAT_OPERATOR_FORCE_QUALIFY | FORMAT_OPERATOR_INVALID_AS_NULL;
            let oprname = format_operator_extended((*object).objectId, flags);
            if !oprname.is_null() {
                appendStringInfo!(&mut *buffer, "{}",
                    core::ffi::CStr::from_ptr(oprname).to_str().unwrap_or(""));
                if !objname.is_null() {
                    format_operator_parts((*object).objectId, objname, objargs, missing_ok);
                }
            }
        }
        OperatorClassRelationId => {
            let opc_tup = SearchSysCache1(CLAOID, ObjectIdGetDatum((*object).objectId));
            if !HeapTupleIsValid(opc_tup) {
                if !missing_ok { elog!(ERROR, "cache lookup failed for opclass {}", (*object).objectId); }
            } else {
                let opc_form = GETSTRUCT(opc_tup) as Form_pg_opclass;
                let schema = get_namespace_name_or_temp((*opc_form).opcnamespace);
                let am_tup  = SearchSysCache1(AMOID, ObjectIdGetDatum((*opc_form).opcmethod));
                if !HeapTupleIsValid(am_tup) {
                    elog!(ERROR, "cache lookup failed for access method {}", (*opc_form).opcmethod);
                }
                let am_form = GETSTRUCT(am_tup) as Form_pg_am;
                let qname = quote_qualified_identifier(schema, (*opc_form).opcname.data.as_ptr());
                let amname = quote_identifier((*am_form).amname.data.as_ptr());
                appendStringInfo!(&mut *buffer, "{} USING {}",
                    core::ffi::CStr::from_ptr(qname).to_str().unwrap_or(""),
                    core::ffi::CStr::from_ptr(amname).to_str().unwrap_or(""));
                if !objname.is_null() {
                    *objname = list_make3(
                        pstrdup((*am_form).amname.data.as_ptr() as _) as *mut c_void,
                        schema as *mut c_void,
                        pstrdup((*opc_form).opcname.data.as_ptr() as _) as *mut c_void,
                    );
                }
                ReleaseSysCache(am_tup);
                ReleaseSysCache(opc_tup);
            }
        }
        OperatorFamilyRelationId => {
            getOpFamilyIdentity(buffer, (*object).objectId, objname, missing_ok);
        }
        AccessMethodRelationId => {
            let amname = get_am_name((*object).objectId);
            if amname.is_null() {
                if !missing_ok { elog!(ERROR, "cache lookup failed for access method {}", (*object).objectId); }
            } else {
                let qi = quote_identifier(amname);
                appendStringInfo!(&mut *buffer, "{}",
                    core::ffi::CStr::from_ptr(qi).to_str().unwrap_or(""));
                if !objname.is_null() {
                    *objname = list_make1(amname as *mut c_void);
                }
            }
        }
        // amop, amproc, rule, trigger, namespace, statistic, ts-*, role, authmem,
        // database, tablespace, fdw, server, usermapping, defacl, extension,
        // event trigger, parameter acl, policy, publication, pubnamespace,
        // pubrel, subscription, transform
        _ => {
            getObjectIdentityParts_ext2(buffer, object, objname, objargs, missing_ok);
        }
    }
}

