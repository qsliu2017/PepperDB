/*
 * Check ownership of an object previously identified by get_object_address.
 */
pub unsafe fn check_object_ownership(
    roleid: Oid,
    objtype: ObjectType,
    address: ObjectAddress,
    object: *mut Node,
    relation: Relation,
) {
    match objtype {
        OBJECT_INDEX |
        OBJECT_SEQUENCE |
        OBJECT_TABLE |
        OBJECT_VIEW |
        OBJECT_MATVIEW |
        OBJECT_FOREIGN_TABLE |
        OBJECT_COLUMN |
        OBJECT_RULE |
        OBJECT_TRIGGER |
        OBJECT_POLICY |
        OBJECT_TABCONSTRAINT => {
            if !object_ownercheck(RelationRelationId, RelationGetRelid(relation), roleid) {
                aclcheck_error(
                    ACLCHECK_NOT_OWNER,
                    objtype,
                    RelationGetRelationName(relation),
                );
            }
        }
        OBJECT_TYPE |
        OBJECT_DOMAIN |
        OBJECT_ATTRIBUTE => {
            if !object_ownercheck(address.classId, address.objectId, roleid) {
                aclcheck_error_type(ACLCHECK_NOT_OWNER, address.objectId);
            }
        }
        OBJECT_DOMCONSTRAINT => {
            let tuple = SearchSysCache1(CONSTROID, ObjectIdGetDatum(address.objectId));
            if !HeapTupleIsValid(tuple) {
                elog!(ERROR, "constraint with OID {} does not exist", address.objectId);
            }
            let contypid = (*(GETSTRUCT(tuple) as Form_pg_constraint)).contypid;
            ReleaseSysCache(tuple);

            /*
             * Fallback to type ownership check in this case as this is
             * what domain constraints rely on.
             */
            if !object_ownercheck(TypeRelationId, contypid, roleid) {
                aclcheck_error_type(ACLCHECK_NOT_OWNER, contypid);
            }
        }
        OBJECT_AGGREGATE |
        OBJECT_FUNCTION |
        OBJECT_PROCEDURE |
        OBJECT_ROUTINE |
        OBJECT_OPERATOR => {
            if !object_ownercheck(address.classId, address.objectId, roleid) {
                aclcheck_error(
                    ACLCHECK_NOT_OWNER,
                    objtype,
                    NameListToString((*(object as *mut ObjectWithArgs)).objname),
                );
            }
        }
        OBJECT_DATABASE |
        OBJECT_EVENT_TRIGGER |
        OBJECT_EXTENSION |
        OBJECT_FDW |
        OBJECT_FOREIGN_SERVER |
        OBJECT_LANGUAGE |
        OBJECT_PUBLICATION |
        OBJECT_SCHEMA |
        OBJECT_SUBSCRIPTION |
        OBJECT_TABLESPACE => {
            if !object_ownercheck(address.classId, address.objectId, roleid) {
                aclcheck_error(
                    ACLCHECK_NOT_OWNER,
                    objtype,
                    strVal(object as *mut c_void) as *const c_char,
                );
            }
        }
        OBJECT_COLLATION |
        OBJECT_CONVERSION |
        OBJECT_OPCLASS |
        OBJECT_OPFAMILY |
        OBJECT_STATISTIC_EXT |
        OBJECT_TSDICTIONARY |
        OBJECT_TSCONFIGURATION => {
            if !object_ownercheck(address.classId, address.objectId, roleid) {
                aclcheck_error(
                    ACLCHECK_NOT_OWNER,
                    objtype,
                    NameListToString(object as *mut List),
                );
            }
        }
        OBJECT_LARGEOBJECT => {
            if !lo_compat_privileges()
               && !object_ownercheck(address.classId, address.objectId, roleid)
            {
                ereport!(ERROR,
                    errmsg!("must be owner of large object {}", address.objectId));
            }
        }
        OBJECT_CAST => {
            /* We can only check permissions on the source/target types */
            let lst        = object as *mut List;
            let sourcetype = linitial(lst) as *mut TypeName;
            let targettype = lsecond(lst) as *mut TypeName;
            let sourcetypeid = typenameTypeId(core::ptr::null_mut(), sourcetype);
            let targettypeid = typenameTypeId(core::ptr::null_mut(), targettype);

            if !object_ownercheck(TypeRelationId, sourcetypeid, roleid)
               && !object_ownercheck(TypeRelationId, targettypeid, roleid)
            {
                ereport!(ERROR,
                    errmsg!("must be owner of type or type"));
            }
        }
        OBJECT_TRANSFORM => {
            let typename = linitial(object as *mut List) as *mut TypeName;
            let typeid   = typenameTypeId(core::ptr::null_mut(), typename);
            if !object_ownercheck(TypeRelationId, typeid, roleid) {
                aclcheck_error_type(ACLCHECK_NOT_OWNER, typeid);
            }
        }
        OBJECT_ROLE => {
            /*
             * We treat roles as being "owned" by those with CREATEROLE priv,
             * provided that they also have admin option on the role.
             *
             * However, superusers are only owned by superusers.
             */
            if superuser_arg(address.objectId) {
                if !superuser_arg(roleid) {
                    ereport!(ERROR,
                        errmsg!("permission denied"));
                }
            } else {
                if !has_createrole_privilege(roleid) {
                    ereport!(ERROR,
                        errmsg!("permission denied"));
                }
                if !is_admin_of_role(roleid, address.objectId) {
                    ereport!(ERROR,
                        errmsg!("permission denied"));
                }
            }
        }
        OBJECT_TSPARSER |
        OBJECT_TSTEMPLATE |
        OBJECT_ACCESS_METHOD |
        OBJECT_PARAMETER_ACL => {
            /* We treat these object types as being owned by superusers */
            if !superuser_arg(roleid) {
                ereport!(ERROR,
                    errmsg!("must be superuser"));
            }
        }
        OBJECT_AMOP |
        OBJECT_AMPROC |
        OBJECT_DEFAULT |
        OBJECT_DEFACL |
        OBJECT_PUBLICATION_NAMESPACE |
        OBJECT_PUBLICATION_REL |
        OBJECT_USER_MAPPING => {
            /* These are currently not supported or don't make sense here. */
            elog!(ERROR, "unsupported object type: {}", objtype as c_int);
        }
        _ => {
            elog!(ERROR, "unsupported object type: {}", objtype as c_int);
        }
    }
}

/*
 * get_object_namespace
 *
 * Find the schema containing the specified object.  For non-schema objects,
 * this function returns InvalidOid.
 */
pub unsafe fn get_object_namespace(address: *const ObjectAddress) -> Oid {
    let cache: c_int;
    let tuple: HeapTuple;
    let oid: Oid;
    let property: *const ObjectPropertyType;

    /* If not owned by a namespace, just return InvalidOid. */
    property = get_object_property_data((*address).classId);
    if (*property).attnum_namespace == InvalidAttrNumber {
        return InvalidOid;
    }

    /* Currently, we can only handle object types with system caches. */
    cache = (*property).oid_catcache_id;
    Assert!(cache != -1);

    /* Fetch tuple from syscache and extract namespace attribute. */
    tuple = SearchSysCache1(cache, ObjectIdGetDatum((*address).objectId));
    if !HeapTupleIsValid(tuple) {
        elog!(ERROR, "cache lookup failed for cache {} oid {}", cache, (*address).objectId);
    }
    oid = DatumGetObjectId(SysCacheGetAttrNotNull(
        cache,
        tuple,
        (*property).attnum_namespace,
    ));
    ReleaseSysCache(tuple);

    oid
}

/*
 * Return ObjectType for the given object type as given by
 * getObjectTypeDescription; if no valid ObjectType code exists, but it's a
 * possible output type from getObjectTypeDescription, return -1.
 * Otherwise, an error is thrown.
 */
pub unsafe fn read_objtype_from_string(objtype: *const c_char) -> c_int {
    let s = core::ffi::CStr::from_ptr(objtype).to_str().unwrap_or("");
    for entry in OBJECT_TYPE_MAP {
        if entry.tm_name == s {
            return entry.tm_type;
        }
    }
    ereport!(ERROR,
        errmsg!("unrecognized object type \"{}\"", s));

    -1  /* keep compiler quiet */
}

