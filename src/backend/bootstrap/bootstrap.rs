/// Create the main-fork storage file for a nailed catalog at its bootstrap locator
/// (relfilenode == oid, the current database, pg_default tablespace).
async fn create_catalog_storage(shared: &std::sync::Arc<crate::shared_state::SharedState>, relid: Oid) {
    let loc = crate::storage::relfilelocator::RelFileLocator {
        spcOid: crate::common::relpath::DEFAULTTABLESPACE_OID,
        dbOid: crate::session::current().database_id(),
        relNumber: relid,
    };
    let mut smgr = crate::storage::smgr::SmgrRelation::open(
        loc,
        crate::storage::procnumber::INVALID_PROC_NUMBER,
    );
    smgr.create(shared, crate::common::relpath::ForkNumber::MAIN_FORKNUM, false).await;
}

/// PG initdb's catalog-population pass, made data-driven (the BKI
/// `create`/`insert`/`build indices` program). Nails the formrdesc catalogs,
/// creates their heap storage, builds pg_type's unique indexes, then seeds the M2
/// base types into pg_type (via `CatalogTupleInsert`, which also fills the indexes).
///
/// After this runs, `SearchSysCache`/the relcache read the REAL on-disk catalogs
/// (a heap or index scan of pg_type/pg_class), so the int2/4/8 lsyscache fallback
/// from step 14 is only the cold-start (pre-initdb) path.
///
/// Must run inside the per-task scope stack (session / xact / snapmgr / relcache /
/// catalog-index registry / WAL insertion). Returns the number of base types
/// seeded.
///
/// STAGED (rules.md s4): the self-describing pg_class/pg_attribute rows for the
/// catalogs themselves, the six `.dat`-backed catalogs (pg_am, pg_namespace, and
/// the rest), and the full `.dat`-driven pg_type/pg_proc seed are deferred to the
/// seed-codegen + non-nailed-catalog initdb; the M2 type-resolution path needs only
/// the base types in pg_type, which are seeded here.
pub async fn bootstrap_catalogs(
    shared: &std::sync::Arc<crate::shared_state::SharedState>,
) -> usize {
    use crate::backend::catalog::index::{index_create, make_index_info};
    use crate::backend::catalog::pg_type::type_create;
    use crate::backend::utils::cache::relcache::{
        relation_cache_initialize_phase3, relation_id_get_relation, relation_close,
    };
    use crate::catalog::pg_namespace::PG_CATALOG_NAMESPACE;
    use crate::catalog::pg_type::{
        TypeNameNspIndexId, TypeOidIndexId, TypeRelationId, TYPCATEGORY_NUMERIC, TYPTYPE_BASE,
    };

    // 1. Nail the formrdesc catalogs (pg_class/pg_attribute/pg_proc/pg_type) so the
    //    relcache can read them before they exist on disk.
    relation_cache_initialize_phase3();

    // 2. Create the nailed catalogs' heap storage.
    for cat in FORMRDESC_CATALOGS {
        create_catalog_storage(shared, cat.relid).await;
    }

    // 3. Build pg_type's unique indexes over the (still empty) heap, so the seed
    //    inserts below populate them (gating decision 3: real btree catalog indexes).
    let pg_type = relation_id_get_relation(TypeRelationId)
        .unwrap_or_else(|| unreachable!("pg_type is nailed"));
    // pg_type_oid_index on (oid), pg_type_typname_nsp_index on (typname, typnamespace).
    let oid_info = make_index_info(&[crate::catalog::pg_type::Anum_pg_type_oid as i16], true);
    index_create(
        shared,
        &pg_type,
        "pg_type_oid_index",
        TypeOidIndexId,
        TypeOidIndexId,
        &oid_info,
        &["oid".to_owned()],
        Oid(403), // btree
        crate::common::relpath::DEFAULTTABLESPACE_OID,
        &[Oid(0)],
        &[Oid(1981)], // oid_ops
        &[0],
        false,
    )
    .await;
    relation_close(pg_type);

    // 4. Seed the M2 base types into pg_type (via CatalogTupleInsert -> heap +
    //    indexes). Each base type's row makes `int4` etc. resolvable by OID and by
    //    name from the real on-disk catalog.
    let types = m2_base_types();
    for ty in &types {
        type_create(
            shared,
            ty.oid,
            ty.name,
            PG_CATALOG_NAMESPACE,
            InvalidOid, // typrelid (base types have no rowtype relation)
            0,          // relation kind: none
            Oid(10),    // owner (bootstrap superuser)
            ty.len,
            TYPTYPE_BASE,
            ty.category,
            ty.preferred,
            b',' as i8,
            ty.input,
            ty.output,
            InvalidOid,
            InvalidOid,
            InvalidOid,
            InvalidOid,
            InvalidOid,
            InvalidOid,
            InvalidOid,
            false,
            InvalidOid, // array type (staged)
            InvalidOid,
            None,
            None,
            ty.byval,
            ty.align,
            ty.storage,
            -1,
            0,
            false,
            InvalidOid,
        )
        .await;
    }

    let _ = (TYPCATEGORY_NUMERIC, TypeNameNspIndexId); // (name index built with the table-create path)

    // 5. M3: bring up pg_proc + pg_operator (storage, indexes, seed rows) so the
    //    operator/function resolution syscaches resolve int4 +/>/etc. (the pg_proc
    //    seed also includes the M4 cast-support functions.)
    seed_pg_proc_m3(shared).await;
    seed_pg_operator_m3(shared).await;
    // 5b. M4 (step 23): bring up pg_cast (storage, indexes, seed rows) so
    //     find_coercion_pathway resolves int4->numeric/float8 etc. via pg_cast.
    seed_pg_cast_m4(shared).await;
    // 5c. M5 (step 25B): seed the aggregate support pg_proc rows + pg_aggregate so
    //     nodeAgg's AGGFNOID lookup resolves count/sum/min/max transfns.
    seed_pg_proc_m5_agg(shared).await;
    seed_pg_aggregate_m5(shared).await;

    // 6. Warm the operator/function-resolution syscaches for the seeded M3 set.
    //    The parser's operator resolution (make_op -> oper -> OpernameGetOprid) runs
    //    in SYNC context (transformExpr), so it can only hit ALREADY-WARM catcache
    //    entries (the index-scan miss path is async; staged). PG warms its critical
    //    caches at startup (InitCatalogCachePhase2); here we warm exactly the M3
    //    OPERNAMENSP / OPEROID / PROCOID / PROCNAMEARGSNSP entries the int4 operator
    //    and function resolution needs.
    //
    //    Make the just-inserted seed rows visible to the warm scans first: bump the
    //    command counter and drop the stale catalog snapshot so each warm heap-scan
    //    takes a fresh catalog snapshot that sees the new pg_operator/pg_proc rows.
    crate::backend::access::transam::xact::CommandCounterIncrement();
    crate::backend::utils::time::snapmgr::InvalidateCatalogSnapshot();
    warm_m3_resolution_caches(shared).await;

    types.len()
}

/// Warm the M3 operator/function resolution syscaches (OPERNAMENSP / OPEROID /
/// PROCOID / PROCNAMEARGSNSP) for the seeded int4 operators + support functions,
/// so the SYNC parser resolution path hits them. PG `InitCatalogCachePhase2` analog
/// for the M3-critical caches.
async fn warm_m3_resolution_caches(shared: &std::sync::Arc<crate::shared_state::SharedState>) {
    use crate::backend::catalog::heap::name_data;
    use crate::backend::utils::cache::syscache::{release_sys_cache, search_sys_cache_populate};
    use crate::catalog::pg_namespace::PG_CATALOG_NAMESPACE;
    use crate::postgres::{NameGetDatum, ObjectIdGetDatum, PointerGetDatum};
    use crate::utils::syscache::SysCacheIdentifier as Sc;

    for op in SEED_PG_OPERATOR_M3 {
        // OPERNAMENSP (oprname, oprleft, oprright, oprnamespace).
        let nd = name_data(op.name);
        let keys = [
            NameGetDatum(&nd),
            ObjectIdGetDatum(Oid(op.left)),
            ObjectIdGetDatum(Oid(op.right)),
            ObjectIdGetDatum(PG_CATALOG_NAMESPACE),
        ];
        if let Some(t) = search_sys_cache_populate(shared, Sc::OPERNAMENSP, &keys).await {
            release_sys_cache(t);
        }
        // OPEROID (oid).
        if let Some(t) =
            search_sys_cache_populate(shared, Sc::OPEROID, &[ObjectIdGetDatum(Oid(op.oid))]).await
        {
            release_sys_cache(t);
        }
    }

    for pr in SEED_PG_PROC_M3.iter().chain(SEED_PG_PROC_M4_CAST) {
        // PROCOID (oid) -- needed by get_func_retset in make_op and by the cast
        // FuncExpr resolution (the cast support functions).
        if let Some(t) =
            search_sys_cache_populate(shared, Sc::PROCOID, &[ObjectIdGetDatum(Oid(pr.oid))]).await
        {
            release_sys_cache(t);
        }
        // PROCNAMEARGSNSP (proname, proargtypes, pronamespace) -- function-by-name.
        let nd = name_data(pr.name);
        let argoids: Vec<Oid> = pr.argtypes.iter().map(|&o| Oid(o)).collect();
        let argvec = crate::utils::builtins::buildoidvector(&argoids);
        let keys = [
            NameGetDatum(&nd),
            PointerGetDatum(argvec.cast::<u8>()),
            ObjectIdGetDatum(PG_CATALOG_NAMESPACE),
        ];
        if let Some(t) = search_sys_cache_populate(shared, Sc::PROCNAMEARGSNSP, &keys).await {
            release_sys_cache(t);
        }
    }

    // M4 (step 23): warm CASTSOURCETARGET for each seeded cast, and TYPEOID for the
    // base types the cast resolution / I/O coercion reads (so the SYNC coercion path
    // -- find_coercion_pathway, getTypeOutputInfo/getTypeInputInfo -- hits a warm
    // cache over the wire).
    for ct in SEED_PG_CAST_M4 {
        let keys = [ObjectIdGetDatum(Oid(ct.source)), ObjectIdGetDatum(Oid(ct.target))];
        if let Some(t) = search_sys_cache_populate(shared, Sc::CASTSOURCETARGET, &keys).await {
            release_sys_cache(t);
        }
    }
    for ty in m2_base_types() {
        if let Some(t) =
            search_sys_cache_populate(shared, Sc::TYPEOID, &[ObjectIdGetDatum(ty.oid)]).await
        {
            release_sys_cache(t);
        }
    }

    // M5 (step 25B): warm AGGFNOID for each seeded aggregate so nodeAgg's sync
    // SearchSysCache1(AGGFNOID) hits at ExecInitAgg time.
    for agg in SEED_PG_AGGREGATE_M5 {
        if let Some(t) =
            search_sys_cache_populate(shared, Sc::AGGFNOID, &[ObjectIdGetDatum(Oid(agg.aggfnoid))]).await
        {
            release_sys_cache(t);
        }
    }
}

