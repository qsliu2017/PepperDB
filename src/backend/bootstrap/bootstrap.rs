//! Bootstrap / initdb support. Translated from
//! `src/backend/bootstrap/bootstrap.c`, but with the BKI text pipeline replaced
//! by `.dat`-driven codegen (gating decision 2 in plan 003).
//!
//! PostgreSQL bootstraps an empty cluster in two cooperating pieces:
//!
//!  - `genbki.pl` reads the catalog `.h` headers + `pg_*.dat` files and writes
//!    `postgres.bki`, a tiny text language of `create`/`open`/`insert` commands
//!    plus `schemapg.h` (compiled-in attribute descriptors for the nailed
//!    catalogs).
//!  - `bootstrap.c` runs in `--boot` mode, parsing `postgres.bki` with a
//!    flex/bison grammar (`bootscanner.l` / `bootparse.y`) and executing it:
//!    `boot_openrel` / `DefineAttr` / `InsertOneTuple` build each catalog heap
//!    and `build_indices` builds the catalog indexes.
//!
//! In this port the BKI TEXT layer disappears. `build.rs` emits the same data
//! directly as Rust:
//!  - [`BootstrapAttr`] arrays (`SCHEMA_PG_*`) -- the schemapg.h analog, the
//!    compiled-in column descriptors for the formrdesc catalogs.
//!  - generic seed rows (`SEED_PG_*`) -- the `insert ( ... )` analog, the initial
//!    contents of the `.dat`-backed M2 catalogs.
//!
//! Two functions matter here:
//!  - [`formrdesc`] builds the hardcoded, compiled-in relation descriptor for a
//!    nailed bootstrap catalog so the relcache can read it before it exists on
//!    disk (breaking the relcache<->disk chicken-and-egg). The TupleDesc part is
//!    fully built from [`BootstrapAttr`] data (it "had better be right because it
//!    will never be replaced"); the `RelationData`/relcache-insert wrapper stages
//!    against the relcache (step 14).
//!  - the initdb entry point ([`bootstrap_catalogs`]) writes the seed rows into
//!    the catalog heaps and builds the catalog indexes. The heap-write and
//!    index-build calls stage against the heap-AM stubs (steps 11-13/15).
//!
//! `bootparse.y` / `bootscanner.l` are TOMBSTONED (see the note at the bottom):
//! the BKI bison parser is replaced by the `.dat` codegen, so there is nothing to
//! translate.


