/// Build the compiled-in `TupleDesc` for a nailed bootstrap catalog from its
/// [`BootstrapAttr`] schema. This is the load-bearing half of PG `formrdesc`: the
/// attribute data "had better be right because it will never be replaced" -- it
/// comes from the catalog headers via genbki, here via [`BootstrapAttr`].
///
/// Faithful to the `formrdesc` tupdesc loop: start from a template, copy each
/// attribute's fixed-part fields, set `attrelid`, mark the first attribute's
/// `attcacheoff = 0`, populate the compact-attribute cache, and record the
/// composite type identity.
///
/// PG `formrdesc` (the `CreateTemplateTupleDesc` + per-attr `memcpy` + first
/// `attcacheoff` + `populate_compact_attribute` portion). `relid` is the owning
/// catalog OID, which genbki stamps into every `attrelid` (PG's formrdesc reads
/// it back from `attrs[0].attrelid` to set `RelationGetRelid`).
#[must_use]
pub fn formrdesc_tupdesc(relid: Oid, reltype: Oid, attrs: &[BootstrapAttr]) -> TupleDesc {
    use crate::access::tupdesc::{
        CompactAttribute, TupleConstr, ATTNULLABLE_UNRESTRICTED, ATTNULLABLE_VALID,
    };
    use crate::c::{NameData, NAMEDATALEN};
    use crate::catalog::pg_type::{
        TYPALIGN_CHAR, TYPALIGN_DOUBLE, TYPALIGN_INT, TYPALIGN_SHORT, TYPSTORAGE_PLAIN,
    };
    use crate::pg_config::{ALIGNOF_DOUBLE, ALIGNOF_INT, ALIGNOF_SHORT};
    use crate::postgres_ext::Oid as OidT;

    /// Write `name` into a `NameData`, NUL-padded to `NAMEDATALEN` (C namestrcpy).
    fn namestrcpy(name: &mut NameData, src: &str) {
        let bytes = src.as_bytes();
        let n = bytes.len().min(NAMEDATALEN - 1);
        name.data = [0u8; NAMEDATALEN];
        name.data[..n].copy_from_slice(&bytes[..n]);
    }

    let natts = i32::try_from(attrs.len()).unwrap_or(0);
    let mut desc = TupleDescData::create_template(natts);
    desc.tdrefcount = 1; // mark as refcounted (formrdesc nails the entry)
    desc.tdtypeid = reltype;
    desc.tdtypmod = -1;

    let mut has_not_null = false;
    for (i, a) in attrs.iter().enumerate() {
        // Fill the fixed part directly from the compiled-in descriptor; mirrors the
        // `memcpy(TupleDescAttr(...), &attrs[i], ATTRIBUTE_FIXED_PART_SIZE)` in
        // formrdesc, field-by-field (no layout-punning needed).
        let att = &mut desc.attrs[i];
        att.attrelid = relid;
        namestrcpy(&mut att.attname, a.attname);
        att.atttypid = OidT(a.atttypid);
        att.attlen = a.attlen;
        att.attnum = a.attnum;
        att.attndims = a.attndims;
        att.attbyval = a.attbyval;
        att.attalign = a.attalign;
        att.attstorage = a.attstorage;
        att.attnotnull = a.attnotnull;
        att.attcollation = OidT(a.attcollation);
        att.attislocal = true;
        att.atttypmod = -1;
        has_not_null |= a.attnotnull;

        // Build the compact-attribute cache entry. We compute it inline rather
        // than calling `TupleDescData::populate_compact_attribute`, whose catalog
        // branch routes through `IsCatalogRelationOid` (not yet translated). Every
        // formrdesc relation IS a catalog, so a NOT NULL column is ATTNULLABLE_VALID
        // -- exactly what that branch returns for a catalog relid -- which lets the
        // nailed bootstrap descriptors be built before catalog.c lands.
        let alignby = match a.attalign {
            x if x == TYPALIGN_INT => u8::try_from(ALIGNOF_INT).unwrap_or(0),
            x if x == TYPALIGN_CHAR => 1,
            x if x == TYPALIGN_DOUBLE => u8::try_from(ALIGNOF_DOUBLE).unwrap_or(0),
            x if x == TYPALIGN_SHORT => u8::try_from(ALIGNOF_SHORT).unwrap_or(0),
            _ => 0,
        };
        desc.compact_attrs[i] = CompactAttribute {
            attcacheoff: -1,
            attlen: a.attlen,
            attbyval: a.attbyval,
            attispackable: a.attstorage != TYPSTORAGE_PLAIN,
            atthasmissing: false,
            attisdropped: false,
            attgenerated: false,
            attnullability: if a.attnotnull { ATTNULLABLE_VALID } else { ATTNULLABLE_UNRESTRICTED },
            attalignby: alignby,
        };
    }

    // First attribute's attcacheoff is 0 (cf RelationBuildTupleDesc / formrdesc).
    if let Some(first) = desc.compact_attrs.first_mut() {
        first.attcacheoff = 0;
    }

    if has_not_null {
        desc.constr = Some(Box::new(TupleConstr {
            defval: Vec::new(),
            check: Vec::new(),
            missing: None,
            has_not_null: true,
            has_generated_stored: false,
            has_generated_virtual: false,
        }));
    }

    std::sync::Arc::new(desc)
}

/// Build (and relcache-insert) the hardcoded relation descriptor for a nailed
/// bootstrap catalog, so it can be read before pg_class is loaded.
///
/// PG `formrdesc`. The TupleDesc -- the part that is never replaced -- is built
/// completely by [`formrdesc_tupdesc`]. The surrounding nailed [`RelationData`]
/// (its `rd_rel` Form_pg_class, relfilenode mapping, lock/physical addressing,
/// `RelationCacheInsert`) belongs to the relcache, which lands in step 14:
/// step 14 calls [`formrdesc_tupdesc`] for each [`FORMRDESC_CATALOGS`] entry to
/// fill the nailed entry's `rd_att`. This function therefore returns the finished
/// descriptor and documents the staged relcache wiring rather than fabricating a
/// raw-pointer `RelationData` the relcache does not yet own.
///
/// [`RelationData`]: crate::utils::rel::RelationData
#[must_use]
pub fn formrdesc(cat: &BootstrapCatalog) -> TupleDesc {
    let desc = formrdesc_tupdesc(cat.relid, cat.reltype, cat.schema);
    // STAGED (step 14, relcache RelationCacheInitializePhase2/3):
    //   let rel = palloc0::<RelationData>(); rel.rd_isnailed = true; rel.rd_refcnt = 1;
    //   rel.rd_rel = palloc0(CLASS_TUPLE_SIZE); namestrcpy(relname); relnamespace =
    //     PG_CATALOG_NAMESPACE; reltype; relisshared = cat.isshared; relkind = 'r';
    //     relnatts = natts; relam = HEAP_TABLE_AM_OID; ...
    //   rel.rd_att = Some(desc);
    //   RelationMapUpdateMap(relid, relid, isshared, true);  // bootstrap: filenode = oid
    //   RelationInitLockInfo(rel); RelationInitPhysicalAddr(rel);
    //   RelationCacheInsert(rel, false);
    // Until then, callers (step 14) take the returned descriptor.
    desc
}

