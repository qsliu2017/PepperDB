// =============================================================================
// TOMBSTONE: bootparse.y + bootscanner.l (the BKI flex/bison grammar).
//
// PostgreSQL's bootstrap mode parses a generated `postgres.bki` text program with
// `bootscanner.l` (flex) and `bootparse.y` (bison), executing `create` / `open` /
// `insert` / `declare index` / `build indices` commands. In this port the BKI
// TEXT layer does not exist: `build.rs` emits the catalog schema (SCHEMA_PG_*)
// and seed rows (SEED_PG_*) directly as Rust data, and `bootstrap_catalogs`
// executes the equivalent program over that data. There is therefore nothing to
// translate from `bootparse.y` / `bootscanner.l` -- they are intentionally NOT
// ported (replaced by the .dat codegen). The old C entry points (`boot_yyparse`,
// `boot_yylex`, `DefineAttr`, `InsertOneTuple`, `boot_openrel`, ...) have no
// counterpart here; their work is done by the data-driven path above.
// =============================================================================

#[cfg(test)]
mod tests {
    use super::*;
    use crate::catalog::genbki::{INT2OID, NAMEOID, OIDOID};
    use crate::catalog::pg_attribute::Natts_pg_attribute;
    use crate::catalog::pg_class::Natts_pg_class;
    use crate::catalog::pg_proc::Natts_pg_proc;
    use crate::catalog::pg_type::Natts_pg_type;

    /// The generated schema arrays must have exactly the attribute count the
    /// `#[derive(Catalog)]` `Natts_pg_*` constants report from the FormData struct
    /// field layout -- i.e. the genbki schema and the struct agree.
    #[test]
    fn schema_attr_counts_match_catalog_structs() {
        assert_eq!(NATTS_PG_TYPE, Natts_pg_type as usize);
        assert_eq!(NATTS_PG_ATTRIBUTE, Natts_pg_attribute as usize);
        assert_eq!(NATTS_PG_PROC, Natts_pg_proc as usize);
        assert_eq!(NATTS_PG_CLASS, Natts_pg_class as usize);
        // and the static arrays carry exactly that many entries.
        assert_eq!(SCHEMA_PG_TYPE.len(), NATTS_PG_TYPE);
        assert_eq!(SCHEMA_PG_CLASS.len(), NATTS_PG_CLASS);
    }

    /// Attribute numbers are 1-based and contiguous in declaration order.
    #[test]
    fn schema_attnums_are_contiguous() {
        for schema in [SCHEMA_PG_TYPE, SCHEMA_PG_ATTRIBUTE, SCHEMA_PG_PROC, SCHEMA_PG_CLASS] {
            for (i, a) in schema.iter().enumerate() {
                assert_eq!(a.attnum as usize, i + 1, "attr {} out of order", a.attname);
            }
        }
    }

    /// Spot-check the genbki morph: the first column of pg_class is `oid` (oid
    /// type, 4-byte by-value), the second `relname` (name, 64-byte by-ref), and
    /// the leading fixed-width columns are NOT NULL (priorfixedwidth rule).
    #[test]
    fn schema_physical_types_match_genbki() {
        let oid_col = &SCHEMA_PG_CLASS[0];
        assert_eq!(oid_col.attname, "oid");
        assert_eq!(oid_col.atttypid, OIDOID.0);
        assert_eq!(oid_col.attlen, 4);
        assert!(oid_col.attbyval);
        assert!(oid_col.attnotnull);

        let name_col = &SCHEMA_PG_CLASS[1];
        assert_eq!(name_col.attname, "relname");
        assert_eq!(name_col.atttypid, NAMEOID.0);
        assert_eq!(name_col.attlen, 64);
        assert!(!name_col.attbyval);
        assert!(name_col.attnotnull);

        // pg_attribute.attlen is int2 (the int16 -> int2 rename path).
        let attlen_col = SCHEMA_PG_ATTRIBUTE
            .iter()
            .find(|a| a.attname == "attlen")
            .expect("attlen column");
        assert_eq!(attlen_col.atttypid, INT2OID.0);
        assert_eq!(attlen_col.attlen, 2);
    }

    /// genbki morph_row_for_pgattr resolves a `foo[]` column through the
    /// auto-generated array type (Catalog.pm GenerateArrayTypes): atttypid is the
    /// element's array_type_oid, attlen -1, by-ref, extended storage, attndims 1,
    /// attalign 'd' iff the element is double-aligned else 'i', and attcollation
    /// C_COLLATION_OID (950) iff the element is collatable else 0.
    #[test]
    fn schema_array_columns_resolve_to_array_type() {
        const D: i8 = b'd' as i8;
        const I: i8 = b'i' as i8;
        const X: i8 = b'x' as i8;
        let find = |schema: &'static [BootstrapAttr], name: &str| -> &'static BootstrapAttr {
            schema.iter().find(|a| a.attname == name).expect("column present")
        };

        // pg_class.relacl -> _aclitem (1034): aclitem is double-aligned and NOT
        // collatable, so attalign 'd', attcollation 0.
        let relacl = find(SCHEMA_PG_CLASS, "relacl");
        assert_eq!(relacl.atttypid, 1034);
        assert_eq!(relacl.attlen, -1);
        assert!(!relacl.attbyval);
        assert_eq!(relacl.attalign, D);
        assert_eq!(relacl.attstorage, X);
        assert_eq!(relacl.attndims, 1);
        assert_eq!(relacl.attcollation, 0);

        // pg_class.reloptions -> _text (1009): text is int-aligned and collatable,
        // so attalign 'i', attcollation C_COLLATION_OID (950) -- genbki always
        // stamps C collation on a collatable catalog column.
        let reloptions = find(SCHEMA_PG_CLASS, "reloptions");
        assert_eq!(reloptions.atttypid, 1009);
        assert_eq!(reloptions.attalign, I);
        assert_eq!(reloptions.attcollation, 950);
        assert_eq!(reloptions.attndims, 1);

        // pg_attribute.attacl -> _aclitem (1034), align 'd', collation 0.
        let attacl = find(SCHEMA_PG_ATTRIBUTE, "attacl");
        assert_eq!(attacl.atttypid, 1034);
        assert_eq!(attacl.attalign, D);
        assert_eq!(attacl.attcollation, 0);

        // pg_proc.proallargtypes -> _oid (1028): oid is not collatable.
        let proallargtypes = find(SCHEMA_PG_PROC, "proallargtypes");
        assert_eq!(proallargtypes.atttypid, 1028);
        assert_eq!(proallargtypes.attalign, I);
        assert_eq!(proallargtypes.attcollation, 0);

        // pg_proc.proargmodes -> _char (1002): char is not collatable; the array
        // is int-aligned (char is single-byte 'c', not 'd').
        let proargmodes = find(SCHEMA_PG_PROC, "proargmodes");
        assert_eq!(proargmodes.atttypid, 1002);
        assert_eq!(proargmodes.attalign, I);
        assert_eq!(proargmodes.attcollation, 0);

        // pg_proc.proargtypes is `oidvector` -- a fixed-ish scalar type (OID 30),
        // NOT an array column, and FORCE_NOT_NULL.
        let proargtypes = find(SCHEMA_PG_PROC, "proargtypes");
        assert_eq!(proargtypes.atttypid, 30);
        assert_eq!(proargtypes.attndims, 1); // oidvector is typcategory 'A'
        assert!(proargtypes.attnotnull);
    }

    /// formrdesc_tupdesc reproduces the formrdesc invariants: right natts, the
    /// composite type id, refcounted, first attcacheoff = 0, and the
    /// has-not-null constraint flag set (every catalog has NOT NULL columns).
    #[test]
    fn formrdesc_tupdesc_pg_class_shape() {
        let cat = FORMRDESC_CATALOGS
            .iter()
            .find(|c| c.relname == "pg_class")
            .expect("pg_class in formrdesc set");
        let desc = formrdesc_tupdesc(cat.relid, cat.reltype, cat.schema);

        assert_eq!(desc.natts as usize, NATTS_PG_CLASS);
        assert_eq!(desc.attrs.len(), NATTS_PG_CLASS);
        assert_eq!(desc.tdtypeid, cat.reltype);
        assert_eq!(desc.tdtypmod, -1);
        assert_eq!(desc.tdrefcount, 1);
        assert_eq!(desc.compact_attrs[0].attcacheoff, 0);
        assert_eq!(desc.attr(0).attname.data[..3].to_vec(), b"oid".to_vec());
        assert_eq!(desc.attr(1).attlen, 64); // relname is a Name
        let constr = desc.constr.as_ref().expect("pg_class has NOT NULL columns");
        assert!(constr.has_not_null);
    }

    /// Every formrdesc catalog builds a descriptor whose natts matches its schema.
    #[test]
    fn formrdesc_builds_all_bootstrap_catalogs() {
        for cat in FORMRDESC_CATALOGS {
            let desc = formrdesc(cat);
            assert_eq!(
                desc.natts as usize,
                cat.schema.len(),
                "{} natts mismatch",
                cat.relname
            );
        }
    }

    /// The seed-row codegen produced the expected M2 catalogs, and the well-known
    /// rows are present and well-formed (ordered (col,value) pairs).
    #[test]
    fn seed_rows_well_formed() {
        // pg_am seeds at least heap + btree.
        assert!(SEED_PG_AM.iter().any(|r| r.contains(&("amname", "heap"))));
        assert!(SEED_PG_AM.iter().any(|r| r.contains(&("amname", "btree"))));
        // pg_namespace seeds pg_catalog + public.
        assert!(SEED_PG_NAMESPACE.iter().any(|r| r.contains(&("nspname", "pg_catalog"))));
        assert!(SEED_PG_NAMESPACE.iter().any(|r| r.contains(&("nspname", "public"))));
        // every row has an oid as its first pair (genbki insert order).
        for r in SEED_PG_AM {
            assert_eq!(r.first().map(|p| p.0), Some("oid"));
        }
        // the int4/oid/name/text btree opclasses are seeded for the catalog indexes.
        assert!(!SEED_PG_OPCLASS.is_empty());
        assert!(!SEED_PG_AMOP.is_empty());
        assert!(!SEED_PG_AMPROC.is_empty());
    }

    /// bootstrap seeds all six .dat-backed M2 catalogs (inventory plumbing).
    #[test]
    fn bootstrap_catalogs_inventory() {
        assert_eq!(bootstrap_seed_inventory(), 6);
    }
}
