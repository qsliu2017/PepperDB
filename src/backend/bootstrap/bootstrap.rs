// which consumes the generated SCHEMA_/SEED_ data directly. These entry points
// are retained (the header re-exports them) and route through that data-driven
// path; the heap-write/index-build calls stage against the heap-AM stubs.

/// PG `BootstrapModeMain`: the `postgres --boot` entry. In this port there is no
/// BKI text to parse; bootstrap is driven by [`bootstrap_catalogs`]. Kept as the
/// named entry point (header re-exported); never returns in PG.
pub fn boot_strap_mode_main(argv: &[String], check_only: bool) -> ! {
    let _ = (argv, check_only);
    // STAGED: the real `postgres --boot` path runs InitPostgres in bootstrap
    // processing mode, then `bootstrap_catalogs`, then bootstrap-commit + proc_exit.
    // Wired when the bootstrap bin/initdb driver lands.
    unimplemented!("BootstrapModeMain: driven by bootstrap_catalogs once initdb bin lands")
}

