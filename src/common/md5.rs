pub const MD5_BUFLEN: usize = 64;

/*
 * Context data for MD5.
 *
 * The C struct uses two anonymous unions plus a flock of `#define` field
 * aliases (md5_sta/md5_stb/.../md5_st8 over md5_st, and md5_n/md5_n8 over
 * md5_count).  We reproduce the exact #[repr(C)] memory layout with two Rust
 * unions, and provide the aliases as #[inline] accessor helpers (named after
 * the C macros) so the implementation reads the same as the original C.
 *
 *	union {
 *		uint32	md5_state32[4];
 *		uint8	md5_state8[16];
 *	} md5_st;
 *	#define md5_sta md5_st.md5_state32[0]   ...etc
 *
 *	union {
 *		uint64	md5_count64;
 *		uint8	md5_count8[8];
 *	} md5_count;
 *	#define md5_n  md5_count.md5_count64
 *	#define md5_n8 md5_count.md5_count8
 */
#[repr(C)]
#[derive(Clone, Copy)]
pub union md5_st_union {
    pub md5_state32: [uint32; 4],
    pub md5_state8: [uint8; 16],
}

#[repr(C)]
#[derive(Clone, Copy)]
pub union md5_count_union {
    pub md5_count64: uint64,
    pub md5_count8: [uint8; 8],
}

#[repr(C)]
#[derive(Clone, Copy)]
pub struct pg_md5_ctx {
    pub md5_st: md5_st_union,
    pub md5_count: md5_count_union,
    pub md5_i: c_uint,
    pub md5_buf: [uint8; MD5_BUFLEN],
}

/*
 * Field-alias accessors corresponding to the C preprocessor `#define`s:
 *   #define md5_sta md5_st.md5_state32[0]
 *   #define md5_stb md5_st.md5_state32[1]
 *   #define md5_stc md5_st.md5_state32[2]
 *   #define md5_std md5_st.md5_state32[3]
 *   #define md5_st8 md5_st.md5_state8
 *   #define md5_n   md5_count.md5_count64
 *   #define md5_n8  md5_count.md5_count8
 *
 * The unions make these unsafe (union field reads).
 */
impl pg_md5_ctx {
    #[inline]
    unsafe fn md5_sta(&self) -> uint32 {
        self.md5_st.md5_state32[0]
    }
    #[inline]
    unsafe fn md5_stb(&self) -> uint32 {
        self.md5_st.md5_state32[1]
    }
    #[inline]
    unsafe fn md5_stc(&self) -> uint32 {
        self.md5_st.md5_state32[2]
    }
    #[inline]
    unsafe fn md5_std(&self) -> uint32 {
        self.md5_st.md5_state32[3]
    }
    #[inline]
    unsafe fn set_md5_sta(&mut self, v: uint32) {
        self.md5_st.md5_state32[0] = v;
    }
    #[inline]
    unsafe fn set_md5_stb(&mut self, v: uint32) {
        self.md5_st.md5_state32[1] = v;
    }
    #[inline]
    unsafe fn set_md5_stc(&mut self, v: uint32) {
        self.md5_st.md5_state32[2] = v;
    }
    #[inline]
    unsafe fn set_md5_std(&mut self, v: uint32) {
        self.md5_st.md5_state32[3] = v;
    }
    /* md5_st8 -> the 16-byte view of the state */
    #[inline]
    unsafe fn md5_st8(&self) -> *const uint8 {
        self.md5_st.md5_state8.as_ptr()
    }
    /* md5_n -> the 64-bit bit-count */
    #[inline]
    unsafe fn md5_n(&self) -> uint64 {
        self.md5_count.md5_count64
    }
    #[inline]
    unsafe fn set_md5_n(&mut self, v: uint64) {
        self.md5_count.md5_count64 = v;
    }
    /* md5_n8 -> the 8-byte view of the bit-count */
    #[inline]
    unsafe fn md5_n8(&self) -> *const uint8 {
        self.md5_count.md5_count8.as_ptr()
    }
}

