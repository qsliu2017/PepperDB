/*
 * #define SHIFT(X, s) (((X) << (s)) | ((X) >> (32 - (s))))
 *
 * This is a 32-bit left-rotate.  In C the shifts/OR wrap modulo 2^32; we use
 * rotate_left to get identical semantics without triggering Rust's debug
 * overflow checks.
 */
#[inline(always)]
fn SHIFT(x: uint32, s: u32) -> uint32 {
    x.rotate_left(s)
}

/*
 * #define F(X, Y, Z) (((X) & (Y)) | ((~X) & (Z)))
 * #define G(X, Y, Z) (((X) & (Z)) | ((Y) & (~Z)))
 * #define H(X, Y, Z) ((X) ^ (Y) ^ (Z))
 * #define I(X, Y, Z) ((Y) ^ ((X) | (~Z)))
 *
 * Bitwise-only; no arithmetic overflow possible, but kept as helpers.
 */
#[inline(always)]
fn F(x: uint32, y: uint32, z: uint32) -> uint32 {
    (x & y) | (!x & z)
}
#[inline(always)]
fn G(x: uint32, y: uint32, z: uint32) -> uint32 {
    (x & z) | (y & !z)
}
#[inline(always)]
fn H(x: uint32, y: uint32, z: uint32) -> uint32 {
    x ^ y ^ z
}
#[inline(always)]
fn I(x: uint32, y: uint32, z: uint32) -> uint32 {
    y ^ (x | !z)
}

/*
 * The four round macros.  Every `+` here adds 32-bit state words, the message
 * schedule X[k], and the sine table T[i]; in C these wrap modulo 2^32, so we
 * MUST use wrapping_add to avoid debug-build overflow panics.
 *
 * #define ROUND1(a, b, c, d, k, s, i) \
 * do { \
 *     (a) = (a) + F((b), (c), (d)) + X[(k)] + T[(i)]; \
 *     (a) = SHIFT((a), (s)); \
 *     (a) = (b) + (a); \
 * } while (0)
 * ... ROUND2 uses G, ROUND3 uses H, ROUND4 uses I.
 *
 * Implemented as macro_rules so the a/b/c/d identifiers (rotated each step,
 * as in the C call sequence) operate on the local A/B/C/D variables.  $X and
 * $T are the message schedule and sine table in scope.
 */
macro_rules! ROUND1 {
    ($a:expr, $b:expr, $c:expr, $d:expr, $k:expr, $s:expr, $i:expr, $X:expr, $T:expr) => {{
        $a = $a
            .wrapping_add(F($b, $c, $d))
            .wrapping_add($X[$k])
            .wrapping_add($T[$i]);
        $a = SHIFT($a, $s);
        $a = $b.wrapping_add($a);
    }};
}
macro_rules! ROUND2 {
    ($a:expr, $b:expr, $c:expr, $d:expr, $k:expr, $s:expr, $i:expr, $X:expr, $T:expr) => {{
        $a = $a
            .wrapping_add(G($b, $c, $d))
            .wrapping_add($X[$k])
            .wrapping_add($T[$i]);
        $a = SHIFT($a, $s);
        $a = $b.wrapping_add($a);
    }};
}
macro_rules! ROUND3 {
    ($a:expr, $b:expr, $c:expr, $d:expr, $k:expr, $s:expr, $i:expr, $X:expr, $T:expr) => {{
        $a = $a
            .wrapping_add(H($b, $c, $d))
            .wrapping_add($X[$k])
            .wrapping_add($T[$i]);
        $a = SHIFT($a, $s);
        $a = $b.wrapping_add($a);
    }};
}
macro_rules! ROUND4 {
    ($a:expr, $b:expr, $c:expr, $d:expr, $k:expr, $s:expr, $i:expr, $X:expr, $T:expr) => {{
        $a = $a
            .wrapping_add(I($b, $c, $d))
            .wrapping_add($X[$k])
            .wrapping_add($T[$i]);
        $a = SHIFT($a, $s);
        $a = $b.wrapping_add($a);
    }};
}

