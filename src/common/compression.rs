// zlib.h:  #define Z_DEFAULT_COMPRESSION  (-1)
#[allow(dead_code)]
const Z_DEFAULT_COMPRESSION: c_int = -1;
// zstd.h:  #define ZSTD_CLEVEL_DEFAULT  3
#[allow(dead_code)]
const ZSTD_CLEVEL_DEFAULT: c_int = 3;

// ----------------------------------------------------------------
//   psprintf shim: format a Rust string into a palloc'd C string
