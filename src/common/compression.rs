/*
 * These values are stored in disk, for example in files generated by pg_dump.
 * Create the necessary backwards compatibility layers if their order changes.
 *
 *   typedef enum pg_compress_algorithm
 *   {
 *       PG_COMPRESSION_NONE,
 *       PG_COMPRESSION_GZIP,
 *       PG_COMPRESSION_LZ4,
 *       PG_COMPRESSION_ZSTD,
 *   } pg_compress_algorithm;
 */
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
#[repr(C)]
pub enum pg_compress_algorithm {
    PG_COMPRESSION_NONE = 0,
    PG_COMPRESSION_GZIP = 1,
    PG_COMPRESSION_LZ4 = 2,
    PG_COMPRESSION_ZSTD = 3,
}
// Bring the variants into scope so the body can name them bare, as the C does.
pub use pg_compress_algorithm::*;

// #define PG_COMPRESSION_OPTION_WORKERS        (1 << 0)
pub const PG_COMPRESSION_OPTION_WORKERS: uint32 = 1 << 0;
// #define PG_COMPRESSION_OPTION_LONG_DISTANCE  (1 << 1)
pub const PG_COMPRESSION_OPTION_LONG_DISTANCE: uint32 = 1 << 1;

/*
 *   typedef struct pg_compress_specification
 *   {
 *       pg_compress_algorithm algorithm;
 *       unsigned    options;        - OR of PG_COMPRESSION_OPTION constants
 *       int         level;
 *       int         workers;
 *       bool        long_distance;
 *       char       *parse_error;    - NULL if parsing was OK, else message
 *   } pg_compress_specification;
 */
#[repr(C)]
pub struct pg_compress_specification {
    pub algorithm: pg_compress_algorithm,
    /// OR of PG_COMPRESSION_OPTION constants
    pub options: uint32,
    pub level: c_int,
    pub workers: c_int,
    pub long_distance: bool,
    /// NULL if parsing was OK, else message
    pub parse_error: *mut c_char,
}

impl Default for pg_compress_specification {
    fn default() -> Self {
        pg_compress_specification {
            algorithm: PG_COMPRESSION_NONE,
            options: 0,
            level: 0,
            workers: 0,
            long_distance: false,
            parse_error: null_mut(),
        }
    }
}

