//! Translation of postgres/src/common/compression.c
//!                + postgres/src/include/common/compression.h (the
//!                  pg_compress_algorithm enum + pg_compress_specification
//!                  struct + the PG_COMPRESSION_OPTION_* flag bits)
//!
//! compression.c
//!   Shared code for compression methods and specifications.
//!
//! A compression specification specifies the parameters that should be used
//! when performing compression with a specific algorithm. The simplest
//! possible compression specification is an integer, which sets the
//! compression level.
//!
//! Otherwise, a compression specification is a comma-separated list of items,
//! each having the form keyword or keyword=value.
//!
//! Currently, the supported keywords are "level", "long", and "workers".
//!
//! Portions Copyright (c) 1996-2025, PostgreSQL Global Development Group
//!
//! IDENTIFICATION
//!   src/common/compression.c
//!
//! Port notes:
//!   - This unit is pure string parsing of a compression *specification*; it
//!     does no actual compression. We translate the BACKEND path (`#ifndef
//!     FRONTEND`) which uses palloc/pstrdup; `parse_compress_options` lives
//!     under `#ifdef FRONTEND` in the C, but it is pure string slicing with no
//!     backend-only dependency, so we port it REAL as well.
//!   - The C `_()` gettext macro is a translation no-op at runtime; we drop it
//!     and build the literal message text directly.
//!   - The C uses `psprintf()`/`pstrdup()` to build `result->parse_error`. The
//!     crate has no psprintf, so we provide a local `psprintf_into` helper that
//!     formats a Rust `String`, then copies it into a palloc'd, NUL-terminated
//!     C buffer (matching psprintf's palloc-owned `char *` contract; the caller
//!     may pfree it).
//!   - zstd.h / zlib.h are #included in the C only for level-bound constants
//!     and the default-level macros. liblz4 / libzstd / libz are NOT built here
//!     (USE_LZ4 / USE_ZSTD / HAVE_LIBZ are all undefined), so:
//!       * parse_compress_specification sets parse_error for LZ4/ZSTD/GZIP to
//!         "this build does not support compression with %s", exactly as the C
//!         #else branches do.
//!       * The default-level for gzip (Z_DEFAULT_COMPRESSION) and zstd
//!         (ZSTD_CLEVEL_DEFAULT) is gated behind HAVE_LIBZ / USE_ZSTD in the C,
//!         so in this build `result->level` stays at its prior value in those
//!         #else branches -- we reproduce that (no default-level assignment).
//!       * validate_compress_specification's ZSTD bounds (ZSTD_maxCLevel /
//!         ZSTD_minCLevel) are inside `#ifdef USE_ZSTD`, so they are skipped
//!         here, leaving min_level=1, max_level=1, default_level=0 for ZSTD.
//!   - C `char *` keyword/value/specification args are kept as `*mut c_char`.
//!     pg_strcasecmp, strcmp, strtol, strchr, memcpy, strlen are bound to libc
//!     / the crate's port routine, matching the C exactly.

