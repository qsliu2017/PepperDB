/*
 * Look up a compression algorithm by name. Returns true and sets *algorithm
 * if the name is recognized. Otherwise returns false.
 */
pub unsafe fn parse_compress_algorithm(
    name: *mut c_char,
    algorithm: *mut pg_compress_algorithm,
) -> bool {
    if strcmp(name, c"none".as_ptr()) == 0 {
        *algorithm = PG_COMPRESSION_NONE;
    } else if strcmp(name, c"gzip".as_ptr()) == 0 {
        *algorithm = PG_COMPRESSION_GZIP;
    } else if strcmp(name, c"lz4".as_ptr()) == 0 {
        *algorithm = PG_COMPRESSION_LZ4;
    } else if strcmp(name, c"zstd".as_ptr()) == 0 {
        *algorithm = PG_COMPRESSION_ZSTD;
    } else {
        return false;
    }
    true
}

/*
 * Get the human-readable name corresponding to a particular compression
 * algorithm.
 *
 * The C returns a `const char *` to a string literal. We return a *const
 * c_char to a static NUL-terminated byte string with identical contents.
 */
pub unsafe fn get_compress_algorithm_name(algorithm: pg_compress_algorithm) -> *const c_char {
    match algorithm {
        PG_COMPRESSION_NONE => c"none".as_ptr(),
        PG_COMPRESSION_GZIP => c"gzip".as_ptr(),
        PG_COMPRESSION_LZ4 => c"lz4".as_ptr(),
        PG_COMPRESSION_ZSTD => c"zstd".as_ptr(),
        // no default, to provoke compiler warnings if values are added
    }
    // The C has a trailing `Assert(false); return "???";` after the switch,
    // unreachable because the match above is exhaustive.
}

/*
 * Parse a compression specification for a specified algorithm.
 *
 * See the file header comments for a brief description of what a compression
 * specification is expected to look like.
 *
 * On return, all fields of the result object will be initialized.
 * In particular, result->parse_error will be NULL if no errors occurred
 * during parsing, and will otherwise contain an appropriate error message.
 * The caller may free this error message string using pfree, if desired.
 * Note, however, even if there's no parse error, the string might not make
 * sense: e.g. for gzip, level=12 is not sensible, but it does parse OK.
 *
 * The compression level is assigned by default if not directly specified
 * by the specification.
 *
 * Use validate_compress_specification() to find out whether a compression
 * specification is semantically sensible.
 */
pub unsafe fn parse_compress_specification(
    algorithm: pg_compress_algorithm,
    specification: *mut c_char,
    result: *mut pg_compress_specification,
) {
    // Initial setup of result object.
    (*result).algorithm = algorithm;
    (*result).options = 0;
    (*result).parse_error = null_mut();

    /*
     * Assign a default level depending on the compression method.  This may
     * be enforced later.
     */
    match (*result).algorithm {
        PG_COMPRESSION_NONE => {
            (*result).level = 0;
        }
        PG_COMPRESSION_LZ4 => {
            // #ifdef USE_LZ4: result->level = 0;  (fast compression mode)
            // #else: this build does not support compression with LZ4
            (*result).parse_error =
                cstring_from_str("this build does not support compression with LZ4");
        }
        PG_COMPRESSION_ZSTD => {
            // #ifdef USE_ZSTD: result->level = ZSTD_CLEVEL_DEFAULT;
            // #else: this build does not support compression with ZSTD
            (*result).parse_error =
                cstring_from_str("this build does not support compression with ZSTD");
        }
        PG_COMPRESSION_GZIP => {
            // #ifdef HAVE_LIBZ: result->level = Z_DEFAULT_COMPRESSION;
            // #else: this build does not support compression with gzip
            (*result).parse_error =
                cstring_from_str("this build does not support compression with gzip");
        }
    }

    // If there is no specification, we're done already.
    if specification.is_null() {
        return;
    }

    // As a special case, the specification can be a bare integer.
    let mut bare_level_endp: *mut c_char = null_mut();
    let bare_level = strtol(specification, &mut bare_level_endp, 10) as c_int;
    if specification != bare_level_endp && *bare_level_endp == 0 {
        (*result).level = bare_level;
        return;
    }

    // Look for comma-separated keyword or keyword=value entries.
    let mut specification = specification;
    loop {
        let kwstart: *mut c_char;
        let mut kwend: *mut c_char;
        let vstart: *mut c_char;
        let mut vend: *mut c_char;
        let kwlen: c_int;
        let vlen: c_int;
        let has_value: bool;
        let keyword: *mut c_char;
        let value: *mut c_char;

        // Figure start, end, and length of next keyword and any value.
        kwstart = specification;
        kwend = specification;
        while *kwend != 0 && *kwend != b',' as c_char && *kwend != b'=' as c_char {
            kwend = kwend.add(1);
        }
        kwlen = kwend.offset_from(kwstart) as c_int;
        if *kwend != b'=' as c_char {
            vstart = null_mut();
            vend = null_mut();
            vlen = 0;
            has_value = false;
        } else {
            vstart = kwend.add(1);
            vend = kwend.add(1);
            while *vend != 0 && *vend != b',' as c_char {
                vend = vend.add(1);
            }
            vlen = vend.offset_from(vstart) as c_int;
            has_value = true;
        }

        // Reject empty keyword.
        if kwlen == 0 {
            (*result).parse_error =
                cstring_from_str("found empty string where a compression option was expected");
            break;
        }

        // Extract keyword and value as separate C strings.
        keyword = palloc((kwlen + 1) as Size) as *mut c_char;
        memcpy(
            keyword as *mut c_void,
            kwstart as *const c_void,
            kwlen as Size,
        );
        *keyword.add(kwlen as usize) = 0;
        if !has_value {
            value = null_mut();
        } else {
            value = palloc((vlen + 1) as Size) as *mut c_char;
            memcpy(value as *mut c_void, vstart as *const c_void, vlen as Size);
            *value.add(vlen as usize) = 0;
        }

        // Handle whatever keyword we found.
        if strcmp(keyword, c"level".as_ptr()) == 0 {
            (*result).level = expect_integer_value(keyword, value, result);

            /*
             * No need to set a flag in "options", there is a default level
             * set at least thanks to the logic above.
             */
        } else if strcmp(keyword, c"workers".as_ptr()) == 0 {
            (*result).workers = expect_integer_value(keyword, value, result);
            (*result).options |= PG_COMPRESSION_OPTION_WORKERS;
        } else if strcmp(keyword, c"long".as_ptr()) == 0 {
            (*result).long_distance = expect_boolean_value(keyword, value, result);
            (*result).options |= PG_COMPRESSION_OPTION_LONG_DISTANCE;
        } else {
            (*result).parse_error = cstring_from_str(&format!(
                "unrecognized compression option: \"{}\"",
                cstr_to_str(keyword)
            ));
        }

        // Release memory, just to be tidy.
        pfree(keyword as *mut c_void);
        if !value.is_null() {
            pfree(value as *mut c_void);
        }

        /*
         * If we got an error or have reached the end of the string, stop.
         *
         * If there is no value, then the end of the keyword might have been
         * the end of the string. If there is a value, then the end of the
         * keyword cannot have been the end of the string, but the end of the
         * value might have been.
         */
        if !(*result).parse_error.is_null()
            || (if vend.is_null() {
                *kwend == 0
            } else {
                *vend == 0
            })
        {
            break;
        }

        // Advance to next entry and loop around.
        specification = if vend.is_null() {
            kwend.add(1)
        } else {
            vend.add(1)
        };
    }
}

/*
 * Parse 'value' as an integer and return the result.
 *
 * If parsing fails, set result->parse_error to an appropriate message
 * and return -1.
 */
unsafe fn expect_integer_value(
    keyword: *mut c_char,
    value: *mut c_char,
    result: *mut pg_compress_specification,
) -> c_int {
    if value.is_null() {
        (*result).parse_error = cstring_from_str(&format!(
            "compression option \"{}\" requires a value",
            cstr_to_str(keyword)
        ));
        return -1;
    }

    let mut ivalue_endp: *mut c_char = null_mut();
    let ivalue = strtol(value, &mut ivalue_endp, 10) as c_int;
    if ivalue_endp == value || *ivalue_endp != 0 {
        (*result).parse_error = cstring_from_str(&format!(
            "value for compression option \"{}\" must be an integer",
            cstr_to_str(keyword)
        ));
        return -1;
    }
    ivalue
}

/*
 * Parse 'value' as a boolean and return the result.
 *
 * If parsing fails, set result->parse_error to an appropriate message
 * and return -1.  The caller must check result->parse_error to determine if
 * the call was successful.
 *
 * Valid values are: yes, no, on, off, 1, 0.
 *
 * Inspired by ParseVariableBool().
 */
unsafe fn expect_boolean_value(
    keyword: *mut c_char,
    value: *mut c_char,
    result: *mut pg_compress_specification,
) -> bool {
    if value.is_null() {
        return true;
    }

    if pg_strcasecmp(value, c"yes".as_ptr()) == 0 {
        return true;
    }
    if pg_strcasecmp(value, c"on".as_ptr()) == 0 {
        return true;
    }
    if pg_strcasecmp(value, c"1".as_ptr()) == 0 {
        return true;
    }

    if pg_strcasecmp(value, c"no".as_ptr()) == 0 {
        return false;
    }
    if pg_strcasecmp(value, c"off".as_ptr()) == 0 {
        return false;
    }
    if pg_strcasecmp(value, c"0".as_ptr()) == 0 {
        return false;
    }

    (*result).parse_error = cstring_from_str(&format!(
        "value for compression option \"{}\" must be a Boolean value",
        cstr_to_str(keyword)
    ));
    false
}

/*
 * Returns NULL if the compression specification string was syntactically
 * valid and semantically sensible.  Otherwise, returns an error message.
 *
 * Does not test whether this build of PostgreSQL supports the requested
 * compression method.
 */
pub unsafe fn validate_compress_specification(
    spec: *mut pg_compress_specification,
) -> *mut c_char {
    // min_level is only reassigned in the USE_ZSTD branch (compiled out here).
    let min_level: c_int = 1;
    let mut max_level: c_int = 1;
    let mut default_level: c_int = 0;

    // If it didn't even parse OK, it's definitely no good.
    if !(*spec).parse_error.is_null() {
        return (*spec).parse_error;
    }

    /*
     * Check that the algorithm expects a compression level and it is within
     * the legal range for the algorithm.
     */
    match (*spec).algorithm {
        PG_COMPRESSION_GZIP => {
            max_level = 9;
            // #ifdef HAVE_LIBZ: default_level = Z_DEFAULT_COMPRESSION; (skipped)
        }
        PG_COMPRESSION_LZ4 => {
            max_level = 12;
            default_level = 0; // fast mode
        }
        PG_COMPRESSION_ZSTD => {
            // #ifdef USE_ZSTD:
            //   max_level = ZSTD_maxCLevel();
            //   min_level = ZSTD_minCLevel();
            //   default_level = ZSTD_CLEVEL_DEFAULT;
            // Not built here, so min_level=1, max_level=1, default_level=0.
        }
        PG_COMPRESSION_NONE => {
            if (*spec).level != 0 {
                return cstring_from_str(&format!(
                    "compression algorithm \"{}\" does not accept a compression level",
                    cstr_to_str(get_compress_algorithm_name((*spec).algorithm))
                ));
            }
        }
    }

    if ((*spec).level < min_level || (*spec).level > max_level) && (*spec).level != default_level {
        return cstring_from_str(&format!(
            "compression algorithm \"{}\" expects a compression level between {} and {} (default at {})",
            cstr_to_str(get_compress_algorithm_name((*spec).algorithm)),
            min_level,
            max_level,
            default_level
        ));
    }

    /*
     * Of the compression algorithms that we currently support, only zstd
     * allows parallel workers.
     */
    if ((*spec).options & PG_COMPRESSION_OPTION_WORKERS) != 0
        && (*spec).algorithm != PG_COMPRESSION_ZSTD
    {
        return cstring_from_str(&format!(
            "compression algorithm \"{}\" does not accept a worker count",
            cstr_to_str(get_compress_algorithm_name((*spec).algorithm))
        ));
    }

    /*
     * Of the compression algorithms that we currently support, only zstd
     * supports long-distance mode.
     */
    if ((*spec).options & PG_COMPRESSION_OPTION_LONG_DISTANCE) != 0
        && (*spec).algorithm != PG_COMPRESSION_ZSTD
    {
        return cstring_from_str(&format!(
            "compression algorithm \"{}\" does not support long-distance mode",
            cstr_to_str(get_compress_algorithm_name((*spec).algorithm))
        ));
    }

    null_mut()
}

/*
 * Basic parsing of a value specified through a command-line option, commonly
 * -Z/--compress.
 *
 * The parsing consists of a METHOD:DETAIL string fed later to
 * parse_compress_specification().  This only extracts METHOD and DETAIL.
 * If only an integer is found, the method is implied by the value specified.
 *
 * NOTE: in the C this is guarded by `#ifdef FRONTEND`; it is pure string
 * slicing and is ported REAL here.
 */
pub unsafe fn parse_compress_options(
    option: *const c_char,
    algorithm: *mut *mut c_char,
    detail: *mut *mut c_char,
) {
    /*
     * Check whether the compression specification consists of a bare integer.
     *
     * For backward-compatibility, assume "none" if the integer found is zero
     * and "gzip" otherwise.
     */
    let mut endp: *mut c_char = null_mut();
    let result = strtol(option, &mut endp, 10);
    if *endp == 0 {
        if result == 0 {
            *algorithm = pstrdup(c"none".as_ptr());
            *detail = null_mut();
        } else {
            *algorithm = pstrdup(c"gzip".as_ptr());
            *detail = pstrdup(option);
        }
        return;
    }

    // Check whether there is a compression detail following the algorithm name.
    let sep = strchr(option, b':' as c_int);
    if sep.is_null() {
        *algorithm = pstrdup(option);
        *detail = null_mut();
    } else {
        let n = sep.offset_from(option) as usize;
        let alg = palloc((n + 1) as Size) as *mut c_char;
        memcpy(alg as *mut c_void, option as *const c_void, n as Size);
        *alg.add(n) = 0;

        *algorithm = alg;
        *detail = pstrdup(sep.add(1));
    }
}

