/// Copy a Rust `&str` into a freshly palloc'd, NUL-terminated C string,
/// mirroring psprintf()'s "returns a palloc'd char*" contract. The caller owns
/// the result and may pfree it (as the C comment on parse_error notes).
unsafe fn cstring_from_str(s: &str) -> *mut c_char {
    let bytes = s.as_bytes();
    let len = bytes.len();
    let p = palloc(len + 1) as *mut c_char;
    if len > 0 {
        memcpy(p as *mut c_void, bytes.as_ptr() as *const c_void, len);
    }
    *p.add(len) = 0;
    p
}

/// Render a `*const c_char` (assumed valid UTF-8 / ASCII) as a Rust `&str` for
/// embedding into an error message via "{}". Used where the C splices a `%s`.
unsafe fn cstr_to_str<'a>(p: *const c_char) -> &'a str {
    let len = strlen(p);
    let slice = core::slice::from_raw_parts(p as *const u8, len);
    // The keywords/values are caller-supplied bytes; fall back lossily-but the
    // common path is ASCII keywords, so from_utf8 succeeds.
    core::str::from_utf8(slice).unwrap_or("")
}

